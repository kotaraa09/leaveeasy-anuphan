// 🔑 วางคีย์ OpenRouter ที่ผู้สอนแจกให้เป็นรายคนตรงนี้
//    ต้องขึ้นต้นด้วย sk-or-  · ยังไม่ใส่ ปุ่ม AI จะขึ้นข้อความบอกว่ายังไม่ได้ใส่คีย์
//
// ⚠️ ใช้ได้เฉพาะคีย์ของหลักสูตรเท่านั้น ห้ามใช้คีย์ส่วนตัวของคุณเอง
//    เพราะไฟล์นี้ถูก commit ขึ้น GitHub คีย์จะติดไปด้วยและใครก็เปิดดูได้
//    ผู้สอนตั้งวงเงินไว้ทุกใบและจะเพิกถอนทั้งหมดเมื่อจบ Module
//
// 📝 Backlog Sprint 2: ย้ายคีย์ AI ไปไว้ฝั่งที่ผู้ใช้แตะไม่ได้ (ตัวกลางฝั่งเซิร์ฟเวอร์)
// ═══════════════════════════════════════════════════════════════
export var คีย์OpenRouter = "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";

// ชื่อรุ่นโมเดลที่หลักสูตรใช้ — ถูกที่สุดในกลุ่มที่ตอบภาษาไทยได้ดี
// ขึ้น 404 ตอนเรียก แปลว่าชื่อรุ่นนี้ใช้ไม่ได้แล้ว ให้เปลี่ยนเป็นชื่อรุ่นสำรองที่ผู้สอนประกาศ
export var รุ่นโมเดล = "google/gemini-2.5-flash-lite";

// รอนานสุดกี่มิลลิวินาทีก่อนยอมแพ้ — ใบงานกำหนดไว้ 15 วินาที
export var รอนานสุด = 15000;

var ปลายทาง = "https://openrouter.ai/api/v1/chat/completions";

// ── ใส่คีย์ไว้หรือยัง ──
// ฝั่งที่เรียกควรถามข้อนี้ก่อน จะได้ขึ้นข้อความที่บอกทางออกได้ตรงกว่ารอให้ยิงแล้วโดน 401
export function มีคีย์ไหม() {
  return คีย์OpenRouter.trim() !== "";
}

// ─────────────────────────────────────────────────────────────
// เรียก AI หนึ่งครั้ง แล้วคืนข้อความที่ AI ตอบกลับมา
//
//   ข้อความระบบ — บอก AI ว่าให้ทำตัวอย่างไรและตอบเป็นรูปแบบไหน
//   ข้อความผู้ใช้ — เนื้อหาจริงที่ให้ AI อ่าน
//
// โยน Error ออกมาเสมอเมื่อไม่สำเร็จ ให้ฝั่งที่เรียกจับแล้วส่งต่อ
// ให้ แปลข้อผิดพลาดAI() ทำเป็นข้อความไทยก่อนขึ้นหน้าจอ
// ─────────────────────────────────────────────────────────────
export async function เรียกAI(ข้อความระบบ, ข้อความผู้ใช้) {
  if (!มีคีย์ไหม()) {
    throw สร้างข้อผิดพลาด("ไม่มีคีย์", "ยังไม่ได้ใส่คีย์ OpenRouter");
  }

  // AbortController คือสวิตช์ยกเลิกของ fetch — ตั้งเวลาไว้ พอครบก็สั่งตัดเอง
  // ไม่มีอันนี้ fetch จะรอไปเรื่อย ๆ ตามใจเครือข่าย
  var ตัวยกเลิก = new AbortController();
  var นาฬิกา = setTimeout(function () { ตัวยกเลิก.abort(); }, รอนานสุด);

  try {
    var คำตอบ = await fetch(ปลายทาง, {
      method: "POST",
      headers: {
        "Authorization": "Bearer " + คีย์OpenRouter,
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        model: รุ่นโมเดล,
        // temperature 0 = ขอให้ตอบแบบเดิมทุกครั้งเมื่อถามด้วยข้อความเดิม
        // งานจัดประเภทต้องการความคงเส้นคงวา ไม่ได้ต้องการความสร้างสรรค์
        temperature: 0,
        messages: [
          { role: "system", content: ข้อความระบบ },
          { role: "user",   content: ข้อความผู้ใช้ }
        ]
      }),
      signal: ตัวยกเลิก.signal
    });

    if (!คำตอบ.ok) {
      // อ่านเนื้อความผิดพลาดมาแนบไว้ด้วย จะได้รู้ว่า OpenRouter บ่นเรื่องอะไร
      var เนื้อ = await คำตอบ.text().catch(function () { return ""; });
      throw สร้างข้อผิดพลาด("สถานะ" + คำตอบ.status, "เรียก AI ไม่สำเร็จ (" + คำตอบ.status + ") " + เนื้อ.slice(0, 200));
    }

    var ผล = await คำตอบ.json();
    var ข้อความ = ผล &&
                 ผล.choices &&
                 ผล.choices[0] &&
                 ผล.choices[0].message &&
                 ผล.choices[0].message.content;

    // ตอบ 200 แต่ไม่มีเนื้อความก็เกิดขึ้นได้ ถือว่าไม่สำเร็จเหมือนกัน
    if (!ข้อความ || !ข้อความ.trim()) {
      throw สร้างข้อผิดพลาด("ตอบว่าง", "AI ตอบกลับมาแต่ไม่มีเนื้อความ");
    }

    return ข้อความ.trim();

  } finally {
    // ปลดนาฬิกาทุกทาง ไม่ว่าจะสำเร็จหรือพัง ไม่งั้นมันจะไปสั่งตัดของรอบถัดไป
    clearTimeout(นาฬิกา);
  }
}

// ── แปลข้อผิดพลาดของ AI ให้อ่านรู้เรื่อง พร้อมบอกทางออก ──
export function แปลข้อผิดพลาดAI(e) {
  // fetch ที่ถูก AbortController สั่งตัด จะโยน error ชื่อ AbortError ออกมา
  if (e && e.name === "AbortError") {
    return "AI ตอบช้าเกิน " + (รอนานสุด / 1000) + " วินาที — ลองกดใหม่อีกครั้ง " +
           "หรือเลือกประเภทการลาเองก็ได้ ยังกดยื่นใบลาได้ตามปกติ";
  }

  var รหัส = (e && e.รหัส) || "";

  if (รหัส === "ไม่มีคีย์") {
    return "ยังไม่ได้ใส่คีย์ OpenRouter — เปิด js/ai.js แล้ววางคีย์ที่ผู้สอนแจกลงในตัวแปร คีย์OpenRouter";
  }
  if (รหัส === "สถานะ401") {
    return "คีย์ OpenRouter ไม่ถูกต้อง — ตรวจว่าคัดลอกมาครบทั้งบรรทัดไหม (ขึ้นต้นด้วย sk-or-)";
  }
  if (รหัส === "สถานะ402") {
    return "วงเงินของคีย์นี้หมดแล้ว — แจ้งผู้สอนเพื่อขอคีย์ใหม่";
  }
  if (รหัส === "สถานะ404") {
    return "ไม่พบรุ่นโมเดล " + รุ่นโมเดล + " — ให้เปลี่ยนเป็นชื่อรุ่นสำรองที่ผู้สอนประกาศในแชท " +
           "(แก้ที่ตัวแปร รุ่นโมเดล ใน js/ai.js)";
  }
  if (รหัส === "สถานะ429") {
    return "เรียก AI ถี่เกินไป — รอสักครู่แล้วกดใหม่อีกครั้ง";
  }
  if (รหัส === "ตอบว่าง") {
    return "AI ตอบกลับมาแต่ไม่มีเนื้อความ — กดใหม่อีกครั้ง";
  }

  // TypeError จาก fetch = ต่อเน็ตไม่ได้เลย (ปิด Wi-Fi ก็จะมาทางนี้)
  if (e && e.name === "TypeError") {
    return "ต่อ AI ไม่ได้ — ตรวจว่าเครื่องต่อเน็ตอยู่ แล้วลองใหม่ " +
           "ระหว่างนี้เลือกประเภทการลาเองแล้วกดยื่นได้ตามปกติ";
  }

  return "เรียก AI ไม่สำเร็จ — " + ((e && e.message) || String(e));
}

// ติดรหัสไว้กับ Error เพื่อให้ แปลข้อผิดพลาดAI() แยกประเภทได้โดยไม่ต้องอ่านข้อความ
function สร้างข้อผิดพลาด(รหัส, ข้อความ) {
  var e = new Error(ข้อความ);
  e.รหัส = รหัส;
  return e;
}
