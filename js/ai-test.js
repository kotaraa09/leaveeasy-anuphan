import { ต้องล็อกอิน } from "./auth.js";
import { เรียกAI, แปลข้อผิดพลาดAI, มีคีย์ไหม, รุ่นโมเดล } from "./ai.js";

(async function () {
  await ต้องล็อกอิน();

  var ปุ่มส่ง = document.getElementById("ปุ่มส่ง");
  var ช่องข้อความ = document.getElementById("ข้อความทดสอบ");
  var กล่องเตือน = document.getElementById("ข้อความเตือน");
  var กล่องคำตอบ = document.getElementById("กล่องคำตอบ");
  var เนื้อคำตอบ = document.getElementById("เนื้อคำตอบ");
  var เวลาที่ใช้ = document.getElementById("เวลาที่ใช้");

  // ยังไม่ได้ใส่คีย์ก็บอกตั้งแต่เปิดหน้า ไม่ต้องรอให้กดแล้วเจอ 401
  if (!มีคีย์ไหม()) {
    แสดงเตือน(กล่องเตือน, แปลข้อผิดพลาดAI({ รหัส: "ไม่มีคีย์" }), "warn");
  }

  ปุ่มส่ง.addEventListener("click", async function () {
    var ข้อความ = ช่องข้อความ.value.trim();
    if (!ข้อความ) {
      แสดงเตือน(กล่องเตือน, "ยังไม่ได้พิมพ์ข้อความที่จะส่งให้ AI");
      ช่องข้อความ.focus();
      return;
    }

    ซ่อนเตือน(กล่องเตือน);
    กล่องคำตอบ.classList.add("hidden");
    กำลังส่ง(true);

    var เริ่มจับเวลา = Date.now();
    try {
      var คำตอบ = await เรียกAI(
        "คุณเป็นผู้ช่วยในระบบลางานของบริษัทไทย ตอบสั้น ๆ เป็นภาษาไทย",
        ข้อความ
      );
      เนื้อคำตอบ.textContent = คำตอบ;
      เวลาที่ใช้.textContent = "ใช้เวลา " + ((Date.now() - เริ่มจับเวลา) / 1000).toFixed(1) +
                              " วินาที · รุ่น " + รุ่นโมเดล;
      กล่องคำตอบ.classList.remove("hidden");
    } catch (ข้อผิดพลาด) {
      // พังแล้วต้องเห็นข้อความ ไม่ใช่ปุ่มค้างหมุนเงียบ ๆ
      แสดงเตือน(กล่องเตือน, แปลข้อผิดพลาดAI(ข้อผิดพลาด));
    } finally {
      // คืนปุ่มให้กดใหม่ได้ทุกทาง — ข้อนี้สำคัญกว่าที่คิด ลองปิด Wi-Fi แล้วกดดู
      กำลังส่ง(false);
    }
  });

  // ระหว่างรอ AI ปิดปุ่มไว้ กันกดซ้ำแล้วยิงซ้อนกันหลายครั้ง (เปลืองวงเงินคีย์ด้วย)
  function กำลังส่ง(อยู่) {
    ปุ่มส่ง.disabled = อยู่;
    ปุ่มส่ง.innerHTML = อยู่
      ? window.ไอคอน("นาฬิกา") + "กำลังถาม AI…"
      : window.ไอคอน("เอไอ") + "ส่งให้ AI";
  }
})();
