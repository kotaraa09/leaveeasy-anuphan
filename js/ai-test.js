// แยกออกมาจากหน้าจริงเพราะเวลาปุ่ม AI ในหน้ายื่นใบลาพัง
// เราต้องตอบให้ได้ก่อนว่า "พังที่การเรียก AI" หรือ "พังที่โค้ดรอบ ๆ"
