// แถบแบ่งสถานะ (segmented control)
//
// ข้างในเป็นปุ่มตัวเลือก <input type="radio"> ธรรมดาที่ถูกซ่อนไว้
// จึงกด Tab เข้ามาแล้วใช้ปุ่มลูกศรเลือกได้เหมือนตัวเลือกทั่วไปทุกประการ
// ส่วนที่มองเห็นคือ <label> ของแต่ละอัน กับเม็ดสีขาวที่เลื่อนไปทับอันที่เลือกอยู่
//
// การเลื่อนของเม็ดสีขาวคือจังหวะเคลื่อนไหวหลักของทั้งระบบ
// มันไม่ได้มีไว้สวย แต่ทำให้ตาตามทันว่าเพิ่งเปลี่ยนจากสถานะไหนไปสถานะไหน
// ─────────────────────────────────────────────────────────────
function แถบแบ่งสถานะ(กล่อง) {
  var ตัวเลือก = Array.prototype.slice.call(กล่อง.querySelectorAll("input[type=radio]"));

  function ที่เลือกอยู่() {
    return ตัวเลือก.find(function (t) { return t.checked; }) || ตัวเลือก[0];
  }

  // เลื่อนเม็ดสีขาวไปทับช่องที่เลือก — CSS เป็นคนเลื่อนจริง เราแค่บอกว่าช่องที่เท่าไร
  function เลื่อนเม็ด() {
    กล่อง.style.setProperty("--seg-index", ตัวเลือก.indexOf(ที่เลือกอยู่()));
  }

  เลื่อนเม็ด();

  return {
    ค่า: function () { return ที่เลือกอยู่().value; },

    // ตั้งค่าจากภายนอก (เช่นค่าที่ติดมาท้าย URL) · ค่าที่ไม่มีในรายการจะถูกเมิน
    ตั้งค่า: function (ค่า) {
      var เป้า = ตัวเลือก.find(function (t) { return t.value === (ค่า || ""); });
      if (!เป้า) return;
      เป้า.checked = true;
      เลื่อนเม็ด();
    },

    // ตัวเลขเล็ก ๆ ท้ายชื่อสถานะ — ช่อง "ทั้งหมด" (value ว่าง) นับทุกใบที่ส่งเข้ามา
    ตั้งจำนวน: function (รายการ) {
      ตัวเลือก.forEach(function (t) {
        var จำนวน = t.value
          ? รายการ.filter(function (ใบ) { return ใบ.status === t.value; }).length
          : รายการ.length;

        var ที่วาง = กล่อง.querySelector('label[for="' + t.id + '"] .n');
        if (ที่วาง) ที่วาง.textContent = จำนวน;
      });
    },

    เมื่อเปลี่ยน: function (ทำอะไร) {
      กล่อง.addEventListener("change", function () {
        เลื่อนเม็ด();
        ทำอะไร();
      });
    }
  };
}
