import { db } from "./firebase-init.js";
import { ต้องล็อกอิน } from "./auth.js";
import { ดูใบลาได้, เป็นผู้ตัดสิน } from "./acl.js";
import { collection, getDocs, query, where } from "https://www.gstatic.com/firebasejs/12.18.0/firebase-firestore.js";

(async function () {
  // ยังไม่ล็อกอินก็เด้งไปหน้าเข้าสู่ระบบ — ต้องหยุดก่อนถึงบรรทัดที่อ่านฐาน
  // ต้องรู้ว่าใครเปิดอยู่ด้วย เพราะผู้ขอลาเห็นได้เฉพาะใบของตัวเอง (ACL.md)
  var ผู้ใช้ = await ต้องล็อกอิน();
  var กล่อง = document.getElementById("ผลลัพธ์");
  var แถบตัวกรอง = document.getElementById("แถบตัวกรอง");
  var ช่องสถานะ = แถบแบ่งสถานะ(document.getElementById("ตัวกรองสถานะ"));
  var ช่องประเภท = document.getElementById("ตัวกรองประเภท");
  var ช่องเรียง = document.getElementById("การเรียง");
  var ปุ่มล้าง = document.getElementById("ปุ่มล้างตัวกรอง");

  var การเรียงเริ่มต้น = "ยื่นใหม่สุด";
  var เห็นทุกคน = เป็นผู้ตัดสิน(ผู้ใช้);

  // ── วิธีเรียงทั้ง 4 แบบ รวมไว้ที่เดียว จะเพิ่มแบบใหม่ก็เติมที่นี่ ──
  // createdAt เก็บเป็นข้อความ "YYYY-MM-DD HH:mm" และ startDate เป็น "YYYY-MM-DD"
  // รูปแบบนี้เรียงด้วยการเทียบข้อความตรง ๆ ได้เลย ไม่ต้องแปลงเป็นวันที่ก่อน
  var วิธีเรียง = {
    "ยื่นใหม่สุด": function (a, b) { return เทียบ(b.createdAt, a.createdAt); },
    "ยื่นเก่าสุด": function (a, b) { return เทียบ(a.createdAt, b.createdAt); },
    "ลาใหม่สุด":  function (a, b) { return เทียบ(b.startDate, a.startDate); },
    "ลาเก่าสุด":  function (a, b) { return เทียบ(a.startDate, b.startDate); }
  };

  // ผู้ขอลาเห็นไม่ครบทั้งระบบ ต้องเขียนบอกไว้ ไม่งั้นจะนึกว่าใบของคนอื่นหายไป
  if (!เห็นทุกคน) {
    document.getElementById("คำอธิบายหน้า").textContent =
      "ใบขอลาที่คุณยื่น · ผู้ขอลาเห็นเฉพาะใบของตัวเองเท่านั้น";
  }

  // ── อ่านใบลาจากฐานข้อมูลจริง ──
  // ระหว่างรอตรงบรรทัดนี้ หน้าจอจะค้างที่โครงร่างสีเทาที่เขียนไว้ใน HTML
  var ใบลาทั้งหมด;
  try {
    ใบลาทั้งหมด = await อ่านใบลาจากฐาน();
  } catch (ข้อผิดพลาด) {
    แสดงข้อผิดพลาด(ข้อผิดพลาด);
    return;                                  // ต่อฐานไม่ได้ ต้องไม่ขึ้น "ยังไม่มีใบขอลาในระบบ"
  }

  เติมตัวเลือกประเภท(ใบลาทั้งหมด);
  ตั้งค่าตั้งต้นจากURL();

  ช่องสถานะ.เมื่อเปลี่ยน(วาดใหม่);
  [ช่องประเภท, ช่องเรียง].forEach(function (ช่อง) {
    ช่อง.addEventListener("change", วาดใหม่);
  });
  ปุ่มล้าง.addEventListener("click", ล้างตัวกรอง);

  วาดใหม่();

  // ── กรอง เรียง แล้ววาดรายการใหม่ · เรียกทุกครั้งที่ผู้ใช้เปลี่ยนตัวเลือก ──
  function วาดใหม่() {
    // ยังไม่มีใบลาสักใบ ตัวกรองก็ไม่มีประโยชน์ ซ่อนไว้ก่อน
    แถบตัวกรอง.classList.toggle("hidden", ใบลาทั้งหมด.length === 0);
    ปุ่มล้าง.classList.toggle("hidden", !กำลังกรองอยู่());

    // ตัวเลขบนแถบแบ่งนับเฉพาะใบที่ผ่านตัวกรองประเภทแล้ว
    // ถ้านับจากทั้งหมดตลอด ผู้ใช้จะเห็นเลข 5 แล้วกดเข้าไปเจอ 2 ใบ — เลขต้องตรงกับสิ่งที่จะได้เห็นจริง
    ช่องสถานะ.ตั้งจำนวน(ใบลาทั้งหมด.filter(ผ่านตัวกรองประเภท));

    var รายการ = ใบลาทั้งหมด.filter(ผ่านตัวกรอง);

    // slice() ก่อน sort เพราะ sort แก้อาร์เรย์เดิม
    // ถ้าเรียงทับของเดิม ลำดับต้นฉบับจะหายไปตั้งแต่การกรองครั้งแรก
    รายการ = รายการ.slice().sort(วิธีเรียง[ช่องเรียง.value] || วิธีเรียง[การเรียงเริ่มต้น]);

    แสดงจำนวน(รายการ.length);
    แสดงรายการ(รายการ);
    จำค่าไว้ในURL();
  }

  function ผ่านตัวกรองประเภท(ใบ) {
    return !ช่องประเภท.value || ใบ.leaveTypeId === ช่องประเภท.value;
  }

  function ผ่านตัวกรอง(ใบ) {
    if (ช่องสถานะ.ค่า() && ใบ.status !== ช่องสถานะ.ค่า()) return false;
    return ผ่านตัวกรองประเภท(ใบ);
  }

  function กำลังกรองอยู่() {
    return ช่องสถานะ.ค่า() !== "" ||
           ช่องประเภท.value !== "" ||
           ช่องเรียง.value !== การเรียงเริ่มต้น;
  }

  function ล้างตัวกรอง() {
    ช่องสถานะ.ตั้งค่า("");
    ช่องประเภท.value = "";
    ช่องเรียง.value = การเรียงเริ่มต้น;
    วาดใหม่();
  }

  // ── เติมรายการเลื่อนลง "ประเภทการลา" จากใบลาที่มีอยู่จริง ──
  // ไม่ได้อ่านจากโฟลเดอร์ leaveTypes เพราะตัวกรองควรมีเฉพาะประเภทที่กรองแล้วเจอใบลา
  // ถ้าใส่ประเภทที่ยังไม่มีใครใช้ ผู้ใช้จะเลือกแล้วเจอรายการว่างโดยไม่รู้ว่าทำอะไรผิด
  function เติมตัวเลือกประเภท(รายการ) {
    var เจอแล้ว = {};

    รายการ.forEach(function (ใบ) {
      if (!ใบ.leaveTypeId || เจอแล้ว[ใบ.leaveTypeId]) return;
      เจอแล้ว[ใบ.leaveTypeId] = true;

      var ตัวเลือก = document.createElement("option");
      ตัวเลือก.value = ใบ.leaveTypeId;
      ตัวเลือก.textContent = ใบ.leaveTypeName || ใบ.leaveTypeId;
      ช่องประเภท.appendChild(ตัวเลือก);
    });
  }

  // ── ค่าที่ติดมาท้าย URL มีสิทธิ์ตั้งค่าตัวเลือกให้ตั้งแต่เปิดหน้า ──
  // ทำให้ลิงก์อย่าง leave-requests.html?status=รอพิจารณา ยังใช้ได้เหมือนเดิม
  // (กล่องตัวเลขบนหน้าแรกลิงก์มาแบบนี้ทุกใบ) และกด F5 แล้วตัวกรองที่เลือกไว้ไม่หาย
  function ตั้งค่าตั้งต้นจากURL() {
    ช่องสถานะ.ตั้งค่า(ค่าจากURL("status"));
    ตั้งถ้ามีตัวเลือกนั้นจริง(ช่องประเภท, ค่าจากURL("type"));
    ตั้งถ้ามีตัวเลือกนั้นจริง(ช่องเรียง, ค่าจากURL("sort"));
  }

  // ค่าท้าย URL แก้ด้วยมือได้ ถ้าใส่ค่าที่ไม่มีในรายการ ต้องไม่ทำให้หน้าจอว่างเปล่า
  // จึงตรวจก่อนว่าเป็นตัวเลือกที่มีอยู่จริง ไม่ใช่ก็ปล่อยให้ใช้ค่าเดิมของช่องนั้น
  function ตั้งถ้ามีตัวเลือกนั้นจริง(ช่อง, ค่า) {
    if (!ค่า) return;
    var มีจริง = Array.prototype.some.call(ช่อง.options, function (o) { return o.value === ค่า; });
    if (มีจริง) ช่อง.value = ค่า;
  }

  // ── เขียนตัวกรองที่เลือกไว้กลับไปท้าย URL ──
  // replaceState = แก้ที่อยู่บนแถบเบราว์เซอร์เฉย ๆ ไม่ได้โหลดหน้าใหม่
  // และไม่เพิ่มประวัติย้อนกลับ ปุ่ม Back จึงยังพากลับหน้าก่อนหน้าตามปกติ
  function จำค่าไว้ในURL() {
    var ค่า = new URLSearchParams();
    if (ช่องสถานะ.ค่า()) ค่า.set("status", ช่องสถานะ.ค่า());
    if (ช่องประเภท.value) ค่า.set("type", ช่องประเภท.value);
    if (ช่องเรียง.value !== การเรียงเริ่มต้น) ค่า.set("sort", ช่องเรียง.value);

    var ที่อยู่ = ค่า.toString() ? location.pathname + "?" + ค่า.toString() : location.pathname;
    history.replaceState(null, "", ที่อยู่);
  }

  // ── บอกจำนวนใบลาที่กำลังแสดงอยู่ ──
  // ตอนกรอง จะบอกทั้งจำนวนที่เห็นและจำนวนทั้งระบบ ผู้ใช้จะได้รู้ว่ามีใบที่ถูกซ่อนไว้อยู่
  // ถ้าไม่มีสักใบ ไม่ต้องขึ้นจำนวน เพราะกล่องสถานะว่างบอกอยู่แล้วว่าไม่เจออะไร
  function แสดงจำนวน(จำนวน) {
    var ที่วาง = document.getElementById("จำนวนใบลา");

    if (จำนวน === 0) {
      ที่วาง.textContent = "";
    } else if (จำนวน === ใบลาทั้งหมด.length) {
      ที่วาง.textContent = "ทั้งหมด " + จำนวน + " ใบ";
    } else {
      ที่วาง.textContent = "แสดง " + จำนวน + " ใบ จากทั้งหมด " + ใบลาทั้งหมด.length + " ใบ";
    }
  }

  // ── ดึงใบลาจากโฟลเดอร์ leaveRequests ──
  async function อ่านใบลาจากฐาน() {
    // 🔑 คำขอต้องตรงกับกฎใน firestore.rules ไม่งั้นได้ permission-denied ทั้งคำขอ
    //    ผู้ขอลา "ขอทั้งโฟลเดอร์" ไม่ได้ เพราะกฎอนุญาตแค่บางใบ
    //    และ Firestore ไม่คัดใบที่ผ่านให้ทีละใบ แต่ปฏิเสธทั้งก้อนทันที
    //    จึงต้องใส่ where ให้ตรงกับเงื่อนไขในกฎ ฐานถึงจะยอมส่งข้อมูลกลับมา
    var คำขอ = เห็นทุกคน
      ? collection(db, "leaveRequests")
      : query(collection(db, "leaveRequests"), where("requesterId", "==", ผู้ใช้.uid));

    var ผล = await getDocs(คำขอ);

    var รายการ = ผล.docs.map(function (ไฟล์) {
      // ไฟล์.id = ชื่อไฟล์ (เช่น "lr001") · ไฟล์.data() = ช่องข้อมูลข้างใน
      // แปะชื่อไฟล์กลับเข้าไปเป็นช่อง id เพื่อให้ตัววาดรายการสร้างลิงก์ได้เหมือนเดิม
      return Object.assign({ id: ไฟล์.id }, ไฟล์.data());
    });

    // กรองซ้ำอีกชั้นด้วยกติกาชุดเดียวกับที่ใช้ซ่อนปุ่ม
    // ฐานคัดมาให้แล้วตั้งแต่ where ข้างบน บรรทัดนี้จึงเป็นตาข่ายชั้นที่สอง
    // เผื่อวันหลังมีคนแก้คำขอข้างบนแล้วลืมแก้ให้ตรงกับกฎ
    return รายการ.filter(function (ใบ) { return ดูใบลาได้(ผู้ใช้, ใบ); });
  }

  // ── ต่อฐานข้อมูลไม่ได้ ต้องบอกสาเหตุ ไม่ใช่ค้างที่โครงร่างสีเทาตลอดไป ──
  function แสดงข้อผิดพลาด(e) {
    var รหัส = (e && e.code) || "";
    var สาเหตุ;

    if (รหัส === "permission-denied") {
      สาเหตุ = "Firestore ปฏิเสธการอ่าน — บัญชีนี้ไม่มีสิทธิ์อ่านข้อมูลชุดนี้ตามกฎใน firestore.rules " +
               "(ผู้ขอลาอ่านได้เฉพาะใบลาของตัวเอง) ถ้าเพิ่งแก้กฎ อย่าลืมกด Publish ที่ Firebase Console";
    } else if (รหัส === "unavailable") {
      สาเหตุ = "ต่อฐานข้อมูลไม่ได้ — ตรวจว่าเครื่องต่อเน็ตอยู่ แล้วกด F5 อีกครั้ง";
    } else if (รหัส === "not-found") {
      สาเหตุ = "ไม่พบฐานข้อมูลของโปรเจกต์นี้ — ตรวจค่าใน js/firebase-init.js";
    } else {
      สาเหตุ = "อ่านข้อมูลไม่สำเร็จ — " + ((e && e.message) || String(e));
    }

    กล่อง.innerHTML = '<div style="padding:20px"><div class="alert alert-error" style="margin:0">' +
                      window.ไอคอน("เตือน") + "<div>" + esc(สาเหตุ) + "</div></div></div>";
  }

  function แสดงรายการ(รายการ) {
    if (รายการ.length === 0) {
      กล่อง.innerHTML = กล่องว่าง();
      var ปุ่มในกล่องว่าง = กล่อง.querySelector("[data-ล้างตัวกรอง]");
      if (ปุ่มในกล่องว่าง) ปุ่มในกล่องว่าง.addEventListener("click", ล้างตัวกรอง);
      return;
    }

    // ผู้ขอลาเห็นแต่ใบของตัวเอง คอลัมน์ "ผู้ขอลา" จึงเป็นชื่อเดิมซ้ำทุกแถว — ตัดทิ้ง
    กล่อง.innerHTML =
      '<div class="data-list' + (เห็นทุกคน ? "" : " no-who") + '">' +
      หัวรายการใบลา() + รายการ.map(แถวใบลา).join("") +
      "</div>";
  }

  // ── สถานะว่าง 3 แบบ ── แต่ละแบบคนละเรื่องกัน ต้องบอกทางออกที่ต่างกันด้วย
  function กล่องว่าง() {
    if (ใบลาทั้งหมด.length > 0) {
      // มีใบลาอยู่ แต่ตัวกรองซ่อนไว้หมด — ทางออกคือล้างตัวกรอง ไม่ใช่ยื่นใบใหม่
      return '<div class="empty">' + window.ไอคอน("รายการ") +
        "<h3>ไม่มีใบลาที่ตรงกับตัวกรอง</h3>" +
        "<p>ลองเลือกสถานะหรือประเภทอื่น หรือล้างตัวกรองเพื่อดูใบลาทั้งหมด " +
        ใบลาทั้งหมด.length + " ใบ</p>" +
        '<div class="btn-row"><button type="button" class="btn-ghost" data-ล้างตัวกรอง>ล้างตัวกรอง</button></div></div>';
    }

    if (เห็นทุกคน) {
      return '<div class="empty">' + window.ไอคอน("กล่องว่าง") +
        "<h3>ยังไม่มีใบขอลาในระบบ</h3>" +
        "<p>เมื่อมีพนักงานยื่นใบลาเข้ามา ใบนั้นจะมาโผล่ที่นี่ให้คุณพิจารณา</p></div>";
    }

    // ผู้ขอลาที่ยังไม่เคยยื่น ต้องไม่เข้าใจว่า "ทั้งระบบไม่มีใบลาเลย"
    return '<div class="empty">' + window.ไอคอน("กล่องว่าง") +
      "<h3>คุณยังไม่มีใบขอลา</h3>" +
      "<p>ยื่นใบแรกได้เลย ใบใหม่จะมีสถานะรอพิจารณาจนกว่าหัวหน้าจะตัดสิน</p>" +
      '<div class="btn-row"><a class="btn" href="new-leave-request.html">ยื่นใบลาใหม่</a></div></div>';
  }

  // เทียบข้อความสองค่าเพื่อใช้เรียงลำดับ
  // ช่องที่ว่างนับเป็นค่าน้อยที่สุด จึงไปกองอยู่ท้ายสุดเวลาเรียงจากใหม่ไปเก่า
  function เทียบ(ก, ข) {
    ก = ก || "";
    ข = ข || "";
    if (ก === ข) return 0;
    return ก < ข ? -1 : 1;
  }
})();

