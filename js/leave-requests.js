// 🔑 จุดที่ต้องระวังที่สุดในไฟล์นี้
//    บน Firestore ช่อง id ไม่ได้อยู่ข้างในไฟล์ แต่ id คือ "ชื่อไฟล์"
//    เวลาอ่านกลับมาจึงต้องเอาชื่อไฟล์มาแปะกลับเป็นช่อง id เอง
//    ถ้าลืม รายการจะขึ้นครบทุกแถวสวยงาม แต่กดแล้วไม่ไปไหน — พังแบบเงียบ ๆ
//
// 🔎 ตัวกรองและการเรียงลำดับทำงานกับข้อมูลที่โหลดมาแล้วในหน่วยความจำ
//    ไม่ได้ยิงถามฐานข้อมูลใหม่ทุกครั้งที่เปลี่ยนตัวเลือก
//    ระบบนี้มีใบลาไม่กี่สิบใบ การกรองในเบราว์เซอร์จึงเร็วกว่าและเสียค่าอ่านน้อยกว่า
