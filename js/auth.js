// 🔑 ต้องเขียน class="hidden" ติดไว้ใน HTML ตั้งแต่แรกเสมอ
//    เพราะกว่า Firebase จะตอบว่าใครล็อกอินอยู่ หน้าจอวาดเสร็จไปแล้ว
//    ถ้าไม่ซ่อนไว้ก่อน เมนูของฝ่ายบุคคลจะแวบให้ทุกคนเห็นเสี้ยววินาทีก่อนหายไป
//
// ⚠️ นี่คือการซ่อนปุ่มบนหน้าจอ ไม่ใช่การกันคนเข้าถึงข้อมูล
//    ใครพิมพ์ที่อยู่หน้าตรง ๆ ก็ยังเปิดเข้ามาได้ หน้านั้นจึงต้องตรวจสิทธิ์ของตัวเองซ้ำอีกชั้น
