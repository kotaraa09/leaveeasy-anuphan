async function ปรับหน้าจอตามบทบาท() {
  var ที่ต้องดู = document.querySelectorAll("[data-เฉพาะบทบาท]");
  if (ที่ต้องดู.length === 0) return;         // หน้านี้ไม่มีอะไรต้องซ่อน

  var ผู้ใช้ = await ผู้ใช้ปัจจุบัน();         // ยังไม่ล็อกอินได้ null — ทุกอย่างจะถูกซ่อนไว้ตามเดิม

  ที่ต้องดู.forEach(function (จุด) {
    var ผ่าน = บทบาทตรงกับ(ผู้ใช้, จุด.getAttribute("data-เฉพาะบทบาท"));
    จุด.classList.toggle("hidden", !ผ่าน);
  });
}

