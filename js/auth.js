import { auth, db } from "./firebase-init.js";
import {
  onAuthStateChanged, signOut
} from "https://www.gstatic.com/firebasejs/12.18.0/firebase-auth.js";
import { doc, getDoc } from "https://www.gstatic.com/firebasejs/12.18.0/firebase-firestore.js";
import { คำไทยของบทบาท, บทบาทตรงกับ } from "./acl.js";

// ── หน้าที่เปิดดูได้โดยไม่ต้องล็อกอิน ──
// นอกเหนือจากรายชื่อนี้ พอโหลด auth.js เข้ามา ยามเฝ้าจะทำงานให้เองทุกหน้า
// เขียนชื่อแบบตัด .html ออก เพราะเซิร์ฟเวอร์ตอนพัฒนาตัด .html ให้เองอัตโนมัติ
var หน้าที่ไม่ต้องล็อกอิน = ["index", "login", "signup"];

// ─────────────────────────────────────────────────────────────
// ส่วนที่ 1 — ใครล็อกอินอยู่
// ─────────────────────────────────────────────────────────────

// รอให้ Firebase ตอบให้เสร็จก่อนว่ามีคนล็อกอินอยู่ไหม แล้วตอบครั้งเดียวจบ
// (onAuthStateChanged ปกติจะคอยรายงานทุกครั้งที่มีการเข้า/ออก เราจึงต้องสั่งเลิกฟังเอง)
export function รอผู้ใช้() {
  return new Promise(function (สำเร็จ) {
    var เลิกฟัง = onAuthStateChanged(auth, function (ผู้ใช้) {
      เลิกฟัง();
      สำเร็จ(ผู้ใช้);
    });
  });
}

// จำโปรไฟล์ที่อ่านมาแล้วไว้ จะได้ไม่ต้องอ่านไฟล์ users ซ้ำหลายรอบในหน้าเดียว
var โปรไฟล์ที่จำไว้ = null;

// คืนข้อมูลคนที่ล็อกอินอยู่ในรูปแบบที่หน้าอื่นเอาไปใช้ได้เลย
// { uid, email, name, role, มีไฟล์ในusers } — ไม่มีคนล็อกอินอยู่คืน null
//
// 🔁 ต้องอ่าน name จากโฟลเดอร์ users เพราะ Firestore ไม่มี JOIN
//    เวลาบันทึกใบลาต้องจดชื่อซ้ำลงไปคู่กับรหัส ไม่งั้นหน้าจอจะขึ้นรหัสยาว ๆ แทนชื่อคน
export async function ผู้ใช้ปัจจุบัน() {
  if (โปรไฟล์ที่จำไว้) return โปรไฟล์ที่จำไว้;

  var ผู้ใช้ = await รอผู้ใช้();
  if (!ผู้ใช้) return null;

  var ไฟล์ = null;
  try {
    ไฟล์ = await getDoc(doc(db, "users", ผู้ใช้.uid));
  } catch (ข้อผิดพลาด) {
    ไฟล์ = null;                              // อ่านโปรไฟล์ไม่ได้ ก็ยังรู้ว่าใครล็อกอินอยู่
  }

  var ข้อมูล = ไฟล์ && ไฟล์.exists() ? ไฟล์.data() : {};

  โปรไฟล์ที่จำไว้ = {
    uid: ผู้ใช้.uid,
    email: ผู้ใช้.email || ข้อมูล.email || "",
    // ยังไม่มีไฟล์ใน users ก็ใช้อีเมลไปก่อน ดีกว่าปล่อยให้ชื่อผู้เขียนในใบลาว่างเปล่า
    name: ข้อมูล.name || ผู้ใช้.email || "ผู้ใช้",
    role: ข้อมูล.role || "employee",
    มีไฟล์ในusers: !!(ไฟล์ && ไฟล์.exists())
  };
  return โปรไฟล์ที่จำไว้;
}

// ─────────────────────────────────────────────────────────────
// ส่วนที่ 2 — ยามเฝ้าหน้า
// ─────────────────────────────────────────────────────────────

// เรียกเป็นบรรทัดแรกของหน้าที่ต้องล็อกอินก่อน
//    var ผู้ใช้ = await ต้องล็อกอิน();
// ล็อกอินอยู่ → คืนโปรไฟล์ให้ใช้ต่อ · ไม่ได้ล็อกอิน → เด้งไปหน้าเข้าสู่ระบบและค้างอยู่ตรงนั้น
export async function ต้องล็อกอิน() {
  var ผู้ใช้ = await รอผู้ใช้();
  if (!ผู้ใช้) {
    ไปหน้าเข้าสู่ระบบ();
    return new Promise(function () {});       // ค้างไว้ ไม่ให้โค้ดบรรทัดถัดไปทำงานต่อ
  }
  return await ผู้ใช้ปัจจุบัน();
}

// พาไปหน้าเข้าสู่ระบบ พร้อมจำไว้ว่าเดิมจะเข้าหน้าไหน จะได้พากลับมาถูกที่หลังล็อกอิน
// ใช้ replace ไม่ใช่ href เพื่อไม่ให้ปุ่มย้อนกลับพาวนกลับมาหน้าที่เข้าไม่ได้อีก
function ไปหน้าเข้าสู่ระบบ() {
  var หน้าเดิม = location.pathname.split("/").pop() + location.search;
  location.replace("login.html?next=" + encodeURIComponent(หน้าเดิม));
}

// ชื่อหน้าปัจจุบันแบบตัด .html ออก — เหตุผลเดียวกับใน js/nav.js
function ชื่อหน้า() {
  return (location.pathname.split("/").pop() || "index").replace(/\.html$/, "");
}

