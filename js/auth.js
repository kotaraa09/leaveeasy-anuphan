export function แปลข้อผิดพลาดAuth(ข้อผิดพลาด) {
  var รหัส = (ข้อผิดพลาด && ข้อผิดพลาด.code) || "";
  return คำแปลข้อผิดพลาด[รหัส] || ("เกิดข้อผิดพลาด (" + (รหัส || "ไม่ทราบสาเหตุ") + ")");
}

// util.js อาจยังไม่ถูกโหลดในบางหน้า จึงมี esc ของตัวเองไว้ใช้ให้ไม่พลาด
function esc(ข้อความ) {
  return String(ข้อความ == null ? "" : ข้อความ)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;")
    .replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

