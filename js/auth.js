async function เติมแถบผู้ใช้() {
  var ที่วาง = document.getElementById("navUser");
  if (!ที่วาง) return;                        // หน้านี้ไม่มีแถบเมนู ก็ไม่ต้องทำอะไร

  var ผู้ใช้ = await ผู้ใช้ปัจจุบัน();

  if (!ผู้ใช้) {
    ที่วาง.innerHTML = '<a class="btn btn-sm" href="login.html">เข้าสู่ระบบ</a>';
    return;
  }

  // วงกลมอักษรย่อ + ชื่อ + บทบาท — บนจอมือถือเหลือแต่วงกลม (ดู .user-chip ใน style.css)
  // อักษรย่อคำนวณที่นี่เอง เพราะ js/util.js ไม่ได้ถูกโหลดในทุกหน้าที่มีแถบเมนู
  var บทบาท = คำไทยของบทบาท[ผู้ใช้.role] || ผู้ใช้.role;
  var คำ = String(ผู้ใช้.name || "?").trim().split(/\s+/);
  var ย่อ = คำ.length === 1 ? คำ[0].slice(0, 2) : คำ[0].slice(0, 1) + คำ[1].slice(0, 1);

  ที่วาง.innerHTML =
    '<span class="user-chip" title="' + esc(ผู้ใช้.name) + " · " + esc(บทบาท) + '">' +
      '<span class="avatar" aria-hidden="true">' + esc(ย่อ) + "</span>" +
      '<span class="who"><b>' + esc(ผู้ใช้.name) + "</b><span>" + esc(บทบาท) + "</span></span>" +
    "</span>" +
    '<button type="button" id="ปุ่มออกจากระบบ" class="btn-plain" aria-label="ออกจากระบบ">' +
      window.ไอคอน("ออก", "ico-sm") + "<span>ออกจากระบบ</span></button>";

  document.getElementById("ปุ่มออกจากระบบ").addEventListener("click", ออกจากระบบ);
}

async function ออกจากระบบ() {
  var ปุ่ม = document.getElementById("ปุ่มออกจากระบบ");
  ปุ่ม.disabled = true;
  try {
    await signOut(auth);
    โปรไฟล์ที่จำไว้ = null;
    location.replace("login.html");           // ออกแล้วต้องกลับมาดูหน้าเดิมด้วยปุ่มย้อนกลับไม่ได้
  } catch (ข้อผิดพลาด) {
    ปุ่ม.disabled = false;
    alert("ออกจากระบบไม่สำเร็จ — " + แปลข้อผิดพลาดAuth(ข้อผิดพลาด));
  }
}

