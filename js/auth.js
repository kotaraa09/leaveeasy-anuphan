// js/auth.js — เรื่องล็อกอินทั้งหมดของระบบ รวมไว้ที่ไฟล์นี้ไฟล์เดียว
//
// ไฟล์นี้ทำ 3 อย่าง
//    1. บอกว่า "ตอนนี้ใครล็อกอินอยู่" พร้อมชื่อและบทบาทที่อ่านจากโฟลเดอร์ users
//    2. เป็นยามเฝ้าหน้า — ยังไม่ล็อกอินก็เด้งไปหน้าเข้าสู่ระบบ ไม่ให้เห็นข้อมูล
//    3. เติมชื่อคนที่ล็อกอินอยู่ + ปุ่มออกจากระบบ ลงแถบเมนูด้านบน
//
// 🔑 จุดที่ต้องระวังที่สุดในไฟล์นี้
//    1. onAuthStateChanged ไม่ได้ตอบทันทีตอนเปิดหน้า
//       Firebase ต้องใช้เวลาเสี้ยววินาทีอ่านการล็อกอินเดิมจากเครื่องก่อน
//       ถ้าถาม auth.currentUser ตรง ๆ ตอนเพิ่งเปิดหน้า จะได้ null ทั้งที่ล็อกอินอยู่
//       แล้วระบบจะเด้งคนที่ล็อกอินอยู่ออกไปหน้าล็อกอินทุกครั้งที่กด F5 — ต้องรอก่อนเสมอ
//    2. ตอนยามเฝ้าไล่ออก ต้องหยุดโค้ดของหน้านั้นให้สนิทด้วย
//       สั่ง location.replace แล้วเบราว์เซอร์ยังไม่เปลี่ยนหน้าทันที โค้ดบรรทัดถัดไปยังวิ่งต่อ
//       จึงคืนคำสัญญาที่ไม่มีวันสำเร็จ (Promise ค้าง) ให้บรรทัดที่ await ค้างอยู่ตรงนั้นจนเปลี่ยนหน้า
