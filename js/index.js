// หน้านี้มีสองหน้าตาซ้อนอยู่ในไฟล์ index.html เดียวกัน แล้วไฟล์นี้เลือกเปิดอันเดียว
//    ยังไม่ล็อกอิน → หน้าต้อนรับ อธิบายว่าระบบทำอะไรและใครทำอะไรได้
//    ล็อกอินแล้ว   → แดชบอร์ด ตัวเลขสรุปและใบลาที่ต้องสนใจตอนนี้
//
// 🔑 หน้าแรกอยู่ในรายชื่อ "หน้าที่ไม่ต้องล็อกอิน" ของ js/auth.js
//    จึงต้องถามด้วย ผู้ใช้ปัจจุบัน() ไม่ใช่ ต้องล็อกอิน()
//    ถ้าเผลอใช้ ต้องล็อกอิน() คนที่ยังไม่มีบัญชีจะถูกเด้งออกทันทีที่เปิดเว็บ
//    และจะไม่มีวันได้เห็นหน้าต้อนรับเลย
//
// 🔒 ตัวเลขบนแดชบอร์ดนับจากใบลาที่ "คนนี้มีสิทธิ์เห็น" เท่านั้น
//    ผู้ขอลาจึงเห็นตัวเลขของตัวเอง ส่วนผู้อนุมัติกับฝ่ายบุคคลเห็นตัวเลขทั้งระบบ
//    เงื่อนไขการอ่านชุดเดียวกับหน้ารายการใบลา เพราะต้องตรงกับ firestore.rules
// ─────────────────────────────────────────────────────────────

import { db } from "./firebase-init.js";
import { ผู้ใช้ปัจจุบัน } from "./auth.js";
import { ดูใบลาได้, ตัดสินใบลาได้, เป็นผู้ตัดสิน, คำไทยของบทบาท } from "./acl.js";
import { collection, getDocs, query, where } from "https://www.gstatic.com/firebasejs/12.18.0/firebase-firestore.js";

(async function () {
  var กำลังตรวจสอบ = document.getElementById("กำลังตรวจสอบ");
  var หน้าต้อนรับ = document.getElementById("หน้าต้อนรับ");
  var แดชบอร์ด = document.getElementById("แดชบอร์ด");

  var ผู้ใช้ = await ผู้ใช้ปัจจุบัน();

  กำลังตรวจสอบ.classList.add("hidden");

  if (!ผู้ใช้) {
    หน้าต้อนรับ.classList.remove("hidden");
    return;                                   // ยังไม่ล็อกอิน ไม่ต้องแตะฐานข้อมูลเลย
  }

  แดชบอร์ด.classList.remove("hidden");
  วาดคำทักทาย(ผู้ใช้);

  var รายการสั้น = document.getElementById("รายการสั้น");
  รายการสั้น.innerHTML = โครงร่างรายการ(3);

  var ใบลาทั้งหมด;
  try {
    ใบลาทั้งหมด = await อ่านใบลาที่เห็นได้(ผู้ใช้);
  } catch (ข้อผิดพลาด) {
    รายการสั้น.innerHTML =
      '<div style="padding:20px">' + กล่องเตือน(อธิบายข้อผิดพลาด(ข้อผิดพลาด)) + "</div>";
    return;
  }

  วาดตัวเลขสรุป(ใบลาทั้งหมด);
  วาดรายการที่ต้องสนใจ(ผู้ใช้, ใบลาทั้งหมด);

  // ── ชื่อคนที่ล็อกอินอยู่ + บทบาท ──
  function วาดคำทักทาย(ผู้ใช้) {
    document.getElementById("คำทักทาย").textContent = "สวัสดี " + ผู้ใช้.name;

    // คนที่ยังไม่มีไฟล์ในโฟลเดอร์ users จะได้บทบาทตั้งต้นเป็นผู้ขอลาไปก่อน
    // ต้องบอกให้รู้ตัว ไม่งั้นจะงงว่าทำไมเมนูของตัวเองไม่เหมือนของเพื่อน
    if (!ผู้ใช้.มีไฟล์ในusers) {
      แดชบอร์ด.insertAdjacentHTML("afterbegin",
        กล่องเตือน("บัญชีนี้ยังไม่มีข้อมูลโปรไฟล์ในระบบ จึงถือเป็นผู้ขอลาไปก่อน — " +
                   "ติดต่อฝ่ายบุคคลถ้าบทบาทของคุณควรเป็นอย่างอื่น", "warn"));
    }
  }

  // ── กล่องตัวเลข 4 ใบ · แต่ละใบเป็นลิงก์เข้าหน้ารายการที่กรองสถานะนั้นไว้แล้ว ──
  // ตัวเลขที่กดไม่ได้คือทางตัน ผู้ใช้เห็นว่ามี 3 ใบรอพิจารณาแล้วต้องไปหาต่อเอง
  function วาดตัวเลขสรุป(รายการ) {
    var นับ = { "รอพิจารณา": 0, "อนุมัติ": 0, "ไม่อนุมัติ": 0 };
    รายการ.forEach(function (ใบ) {
      if (นับ[ใบ.status] !== undefined) นับ[ใบ.status]++;
    });

    var กล่อง = [
      { ชื่อ: "ทั้งหมด", จำนวน: รายการ.length, ที่อยู่: "leave-requests.html" },
      { ชื่อ: "รอพิจารณา", จำนวน: นับ["รอพิจารณา"], ที่อยู่: "leave-requests.html?status=" + encodeURIComponent("รอพิจารณา") },
      { ชื่อ: "อนุมัติ", จำนวน: นับ["อนุมัติ"], ที่อยู่: "leave-requests.html?status=" + encodeURIComponent("อนุมัติ") },
      { ชื่อ: "ไม่อนุมัติ", จำนวน: นับ["ไม่อนุมัติ"], ที่อยู่: "leave-requests.html?status=" + encodeURIComponent("ไม่อนุมัติ") }
    ];

    document.getElementById("กล่องตัวเลข").innerHTML = กล่อง.map(function (ก) {
      return '<a class="stat" href="' + ก.ที่อยู่ + '">' +
        '<span class="label"><span class="dot dot-' + esc(ก.ชื่อ) + '"></span>' + esc(ก.ชื่อ) + "</span>" +
        '<span class="number">' + ก.จำนวน + "</span>" +
        '<span class="foot">' + (ก.จำนวน === 0 ? "ยังไม่มีใบลา" : "ดูรายการ") + "</span>" +
      "</a>";
    }).join("");
  }

  // ── รายการที่ผู้ใช้คนนี้ควรเห็นก่อนใครเพื่อน ──
  // ผู้อนุมัติกับฝ่ายบุคคล: ใบที่รอ "เขา" ตัดสินอยู่ตอนนี้ (ไม่รวมใบของตัวเอง เพราะตัดสินใบตัวเองไม่ได้)
  // ผู้ขอลา: ใบล่าสุดของตัวเอง เรียงจากที่ยื่นใหม่สุด
  function วาดรายการที่ต้องสนใจ(ผู้ใช้, ทั้งหมด) {
    var หัว = document.getElementById("หัวรายการ");
    var สรุป = document.getElementById("สรุปสั้น");
    var ลิงก์ทั้งหมด = document.getElementById("ลิงก์ดูทั้งหมด");
    var รอตัดสิน = เป็นผู้ตัดสิน(ผู้ใช้);

    var รายการ = ทั้งหมด.slice().sort(function (a, b) {
      return (b.createdAt || "") < (a.createdAt || "") ? -1 : 1;
    });

    if (รอตัดสิน) {
      รายการ = รายการ.filter(function (ใบ) { return ตัดสินใบลาได้(ผู้ใช้, ใบ); });
      หัว.textContent = "รอคุณพิจารณา";
      ลิงก์ทั้งหมด.href = "leave-requests.html?status=" + encodeURIComponent("รอพิจารณา");
      สรุป.textContent = รายการ.length === 0
        ? "ไม่มีใบลาที่รอการพิจารณาของคุณ · บทบาท " + (คำไทยของบทบาท[ผู้ใช้.role] || ผู้ใช้.role)
        : "มี " + รายการ.length + " ใบรอการพิจารณาของคุณ";
    } else {
      หัว.textContent = "ใบลาล่าสุดของคุณ";
      สรุป.textContent = ทั้งหมด.length === 0
        ? "คุณยังไม่เคยยื่นใบลาในระบบนี้"
        : "คุณยื่นใบลาไปแล้วทั้งหมด " + ทั้งหมด.length + " ใบ";
    }

    if (รายการ.length === 0) {
      รายการสั้น.innerHTML = รอตัดสิน
        ? สถานะว่าง("ถูก", "ไม่มีอะไรค้างอยู่", "ใบลาทุกใบในระบบถูกพิจารณาไปหมดแล้ว")
        : สถานะว่าง("กล่องว่าง", "ยังไม่มีใบขอลา",
                    "ยื่นใบแรกของคุณได้เลย ใบใหม่จะมีสถานะรอพิจารณาจนกว่าหัวหน้าจะตัดสิน",
                    "new-leave-request.html", "ยื่นใบลาใหม่");
      return;
    }

    // แดชบอร์ดโชว์แค่ 5 ใบแรก ที่เหลือให้กด "ดูทั้งหมด" — หน้าแรกต้องอ่านจบได้ในจอเดียว
    var แสดง = รายการ.slice(0, 5);
    รายการสั้น.innerHTML =
      '<div class="data-list' + (รอตัดสิน ? "" : " no-who") + '">' +
      แสดง.map(แถวใบลา).join("") + "</div>";
  }

  // ── อ่านใบลาเท่าที่บัญชีนี้มีสิทธิ์เห็น ──
  // 🔑 คำขอต้องตรงกับกฎใน firestore.rules ไม่งั้นได้ permission-denied ทั้งคำขอ
  //    ผู้ขอลา "ขอทั้งโฟลเดอร์" ไม่ได้ จึงต้องใส่ where ให้ตรงกับเงื่อนไขในกฎ
  //    (เหตุผลเต็ม ๆ อยู่ในหัวฟังก์ชันเดียวกันของ js/leave-requests.js)
  async function อ่านใบลาที่เห็นได้(ผู้ใช้) {
    var คำขอ = เป็นผู้ตัดสิน(ผู้ใช้)
      ? collection(db, "leaveRequests")
      : query(collection(db, "leaveRequests"), where("requesterId", "==", ผู้ใช้.uid));

    var ผล = await getDocs(คำขอ);

    // ไฟล์.id = ชื่อไฟล์ (เช่น "lr001") ต้องแปะกลับเป็นช่อง id เอง Firestore ไม่ได้เก็บไว้ข้างใน
    return ผล.docs
      .map(function (ไฟล์) { return Object.assign({ id: ไฟล์.id }, ไฟล์.data()); })
      .filter(function (ใบ) { return ดูใบลาได้(ผู้ใช้, ใบ); });
  }

  function สถานะว่าง(ไอคอนชื่อ, หัวข้อ, คำอธิบาย, ที่อยู่, ชื่อปุ่ม) {
    return '<div class="empty">' + window.ไอคอน(ไอคอนชื่อ) +
      "<h3>" + esc(หัวข้อ) + "</h3><p>" + esc(คำอธิบาย) + "</p>" +
      (ที่อยู่ ? '<div class="btn-row"><a class="btn" href="' + ที่อยู่ + '">' + esc(ชื่อปุ่ม) + "</a></div>" : "") +
      "</div>";
  }

  function กล่องเตือน(ข้อความ, ชนิด) {
    return '<div class="alert alert-' + (ชนิด || "error") + '">' + window.ไอคอน("เตือน") +
           "<div>" + esc(ข้อความ) + "</div></div>";
  }

  // ── ต่อฐานข้อมูลไม่ได้ ต้องบอกสาเหตุ ไม่ใช่ปล่อยให้ว่างเปล่า ──
  function อธิบายข้อผิดพลาด(e) {
    var รหัส = (e && e.code) || "";

    if (รหัส === "permission-denied") {
      return "Firestore ปฏิเสธการอ่าน — บัญชีนี้ไม่มีสิทธิ์อ่านข้อมูลชุดนี้ตามกฎใน firestore.rules " +
             "ถ้าเพิ่งแก้กฎ อย่าลืมกด Publish ที่ Firebase Console";
    }
    if (รหัส === "unavailable") return "ต่อฐานข้อมูลไม่ได้ — ตรวจว่าเครื่องต่อเน็ตอยู่ แล้วกด F5 อีกครั้ง";
    if (รหัส === "not-found") return "ไม่พบฐานข้อมูลของโปรเจกต์นี้ — ตรวจค่าใน js/firebase-init.js";
    return "อ่านข้อมูลไม่สำเร็จ — " + ((e && e.message) || String(e));
  }
})();
