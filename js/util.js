function แถวใบลา(ใบ) {
  var วัน = จำนวนวันลา(ใบ.startDate, ใบ.endDate);

  return '<a class="row" href="leave-request-detail.html?id=' + esc(ใบ.id) + '">' +
    '<span class="main">' +
      "<b>" + esc(ใบ.title) + "</b>" +
      '<span class="sub">' + ช่วงวันลา(ใบ.startDate, ใบ.endDate) +
        (วัน ? " · " + วัน + " วัน" : "") + "</span>" +
    "</span>" +
    '<span class="cell">' + esc(ใบ.leaveTypeName || "—") + "</span>" +
    '<span class="st">' + ป้ายสถานะ(ใบ.status) + "</span>" +
    '<span class="who">' + วงอักษรย่อ(ใบ.requesterName) +
      '<span class="who-text"><b>' + esc(ใบ.requesterName || "—") + "</b>" +
      "<span>ยื่น " + (ใบ.createdAt ? วันที่ไทย(ใบ.createdAt.split(" ")[0]) : "—") + "</span></span>" +
    "</span>" +
    window.ไอคอน("ขวา", "chev ico-sm") +
  "</a>";
}

