var เดือนย่อ = ["ม.ค.", "ก.พ.", "มี.ค.", "เม.ย.", "พ.ค.", "มิ.ย.",
               "ก.ค.", "ส.ค.", "ก.ย.", "ต.ค.", "พ.ย.", "ธ.ค."];

// "2026-09-01" → "1 ก.ย. 2026"  ·  "2026-09-01 09:15" → "1 ก.ย. 2026 09:15"
//
// ใช้ปี ค.ศ. ตรงตามที่เก็บในฐาน ไม่แปลงเป็น พ.ศ.
// เพราะถ้าหน้าจอขึ้น 2569 แต่ในฐานเป็น 2026 เวลาไล่ปัญหาจะสับสนว่าเลขไหนคือเลขจริง
function วันที่ไทย(ข้อความ) {
  if (!ข้อความ) return "—";

  var ส่วน = String(ข้อความ).split(" ");
  var วัน = ส่วน[0].split("-");
  if (วัน.length !== 3) return esc(ข้อความ);    // รูปแบบไม่ตรง ก็แสดงค่าเดิมไปตรง ๆ

  var เดือน = เดือนย่อ[Number(วัน[1]) - 1];
  if (!เดือน) return esc(ข้อความ);

  return Number(วัน[2]) + " " + เดือน + " " + วัน[0] + (ส่วน[1] ? " " + ส่วน[1] : "");
}

// นับจำนวนวันลาแบบนับทั้งวันแรกและวันสุดท้าย
// ลาวันที่ 1 ถึงวันที่ 1 = ลา 1 วัน (ไม่ใช่ 0 วัน) เพราะวันนั้นก็ไม่ได้มาทำงาน
function จำนวนวันลา(เริ่ม, สิ้นสุด) {
  if (!เริ่ม || !สิ้นสุด) return 0;

  var ก = new Date(เริ่ม + "T00:00:00");
  var ข = new Date(สิ้นสุด + "T00:00:00");
  if (isNaN(ก) || isNaN(ข)) return 0;

  var วัน = Math.round((ข - ก) / 86400000) + 1;
  return วัน > 0 ? วัน : 0;
}

// ช่วงวันลาแบบอ่านง่าย — วันเดียวไม่ต้องเขียนซ้ำสองครั้ง
function ช่วงวันลา(เริ่ม, สิ้นสุด) {
  if (!เริ่ม && !สิ้นสุด) return "—";
  if (เริ่ม === สิ้นสุด) return วันที่ไทย(เริ่ม);
  return วันที่ไทย(เริ่ม) + " – " + วันที่ไทย(สิ้นสุด);
}

// อักษรย่อสำหรับวงกลมแทนรูปโปรไฟล์
// ชื่อไทยมักเขียนติดกันเป็นคำเดียว การตัดตามช่องว่างจึงได้ตัวเดียวบ่อย ๆ — ยอมรับได้
// เอาไว้ให้แยกคนออกจากกันด้วยหางตา ไม่ได้เอาไว้อ่านชื่อ
function อักษรย่อ(ชื่อ) {
  var คำ = String(ชื่อ || "?").trim().split(/\s+/);
  if (คำ.length === 1) return คำ[0].slice(0, 2);
  return คำ[0].slice(0, 1) + คำ[1].slice(0, 1);
}

// วงกลมอักษรย่อ ใช้แทนรูปโปรไฟล์ทั้งระบบ
function วงอักษรย่อ(ชื่อ, คลาสเพิ่ม) {
  return '<span class="avatar' + (คลาสเพิ่ม ? " " + คลาสเพิ่ม : "") + '" aria-hidden="true">' +
         esc(อักษรย่อ(ชื่อ)) + "</span>";
}

// เขียนข้อความเตือนลงกล่อง .alert แล้วเปิดให้เห็น
// รวมไว้ที่เดียวเพื่อให้ทุกหน้าได้ไอคอนและการจัดวางแบบเดียวกันเสมอ
// (ถ้าปล่อยให้แต่ละหน้าเซ็ต textContent เอง ไอคอนจะหายไปบ้างไม่หายบ้าง)
function แสดงเตือน(กล่อง, ข้อความ, ชนิด) {
  if (!กล่อง) return;
  กล่อง.className = "alert alert-" + (ชนิด || "error");
  กล่อง.innerHTML = window.ไอคอน(ชนิด === "ok" ? "ถูก" : "เตือน") +
                    "<div>" + esc(ข้อความ) + "</div>";
}

function ซ่อนเตือน(กล่อง) {
  if (กล่อง) กล่อง.classList.add("hidden");
}

