// โครงร่างระหว่างรอโหลดข้อมูล — วาดเป็นเงาของแถวจริงที่กำลังจะมา
// ดีกว่าข้อความ "กำลังโหลด…" เพราะบอกล่วงหน้าว่าเนื้อหาจะมาหน้าตาแบบไหน
// และหน้าจอไม่กระตุกตอนของจริงมาแทนที่ เพราะความสูงใกล้เคียงกันอยู่แล้ว
function โครงร่างรายการ(จำนวนแถว) {
  var html = "";
  for (var i = 0; i < (จำนวนแถว || 4); i++) {
    html +=
      '<div class="sk-row">' +
      '<div class="skeleton sk-line" style="width:' + (34 + (i % 3) * 9) + '%"></div>' +
      '<div class="skeleton sk-line" style="width:82px;margin-left:auto"></div>' +
      "</div>";
  }
  return '<div aria-busy="true" aria-label="กำลังโหลดข้อมูล">' + html + "</div>";
}
