// เขียนไว้ที่เดียว สองหน้าจึงหน้าตาเหมือนกันเป๊ะและแก้ครั้งเดียวจบ
//
// ⚠️ แต่ละแถวเป็น <a> จริง ๆ ไม่ใช่ <tr> ที่ดักคลิก
//    คนที่ใช้คีย์บอร์ดเดินหน้าจอจะกด Tab มาถึงและกด Enter เปิดได้เหมือนลิงก์ทั่วไป
