// ปุ่มลืมตาในช่องรหัสผ่าน
//
// เรียกครั้งเดียวตอนหน้าโหลดเสร็จ แล้วทุกช่องที่ห่อด้วย <div class="pw"> จะได้ปุ่มเอง
//
// ⚠️ ปุ่มนี้ต้องเป็น type="button" เสมอ
//    ปุ่มในฟอร์มที่ไม่บอกชนิด เบราว์เซอร์ถือเป็น submit ให้เอง
//    กดดูรหัสผ่านแล้วฟอร์มจะถูกส่งทันที
//
// และสลับเฉพาะ type ของช่องเท่านั้น ไม่แตะค่าข้างใน จึงไม่มีทางที่รหัสผ่านจะหายไประหว่างกด
// ────────────────────────────────────────────────────────────
function ติดปุ่มดูรหัสผ่าน() {
  document.querySelectorAll(".pw").forEach(function (กรอบ) {
    var ช่อง = กรอบ.querySelector("input");
    if (!ช่อง || กรอบ.querySelector(".pw-eye")) return;

    var ปุ่ม = document.createElement("button");
    ปุ่ม.type = "button";
    ปุ่ม.className = "pw-eye";
    กรอบ.appendChild(ปุ่ม);

    วาดปุ่ม(false);
    ปุ่ม.addEventListener("click", function () {
      var กำลังซ่อน = ช่อง.type === "password";
      ช่อง.type = กำลังซ่อน ? "text" : "password";
      วาดปุ่ม(กำลังซ่อน);
      ช่อง.focus();
    });

    // aria-pressed บอกโปรแกรมอ่านหน้าจอว่าตอนนี้กดค้างอยู่หรือเปล่า — รูปไอคอนอย่างเดียวบอกไม่ได้
    function วาดปุ่ม(เห็นอยู่) {
      ปุ่ม.innerHTML = window.ไอคอน(เห็นอยู่ ? "ตาปิด" : "ตา", "ico-sm");
      ปุ่ม.setAttribute("aria-pressed", เห็นอยู่ ? "true" : "false");
      ปุ่ม.setAttribute("aria-label", เห็นอยู่ ? "ซ่อนรหัสผ่าน" : "ดูรหัสผ่าน");
    }
  });
}

