// คำไทยของแต่ละบทบาท — ค่าในฐานเก็บเป็นรหัสอังกฤษเสมอ ส่วนคำไทยใช้แสดงบนหน้าจอ
export var คำไทยของบทบาท = {
  employee: "ผู้ขอลา",
  manager: "ผู้อนุมัติ",
  hr: "ฝ่ายบุคคล"
};

// ─────────────────────────────────────────────────────────────
// คำถามพื้นฐาน 3 ข้อ ที่กติกาข้างล่างทั้งหมดสร้างขึ้นจากนี้
// ─────────────────────────────────────────────────────────────

// ผู้อนุมัติ (manager) และฝ่ายบุคคล (hr) เป็นคนตัดสินใบลาได้ทั้งคู่
export function เป็นผู้ตัดสิน(ผู้ใช้) {
  return !!ผู้ใช้ && (ผู้ใช้.role === "manager" || ผู้ใช้.role === "hr");
}

export function เป็นฝ่ายบุคคล(ผู้ใช้) {
  return !!ผู้ใช้ && ผู้ใช้.role === "hr";
}

// เทียบด้วย requesterId ซึ่งเก็บ uid จริงจาก Firebase Auth
// ⚠️ ใบตัวอย่าง lr001–lr005 เก็บ u001–u003 ที่ไม่ผูกกับบัญชีใคร จึงไม่มีใครเป็นเจ้าของ
export function เป็นเจ้าของใบ(ผู้ใช้, ใบ) {
  return !!ผู้ใช้ && !!ใบ && !!ใบ.requesterId && ใบ.requesterId === ผู้ใช้.uid;
}

// ─────────────────────────────────────────────────────────────
// สิทธิ์รายอย่าง — คู่กับช่อง "ทำได้ / ทำไม่ได้" ใน ACL.md
//
// ทุกข้อคืนคู่กัน 2 ฟังก์ชัน
//    xxxได้()          → true / false เอาไว้ตัดสินว่าจะแสดงปุ่มไหม
//    เหตุผลที่xxxไม่ได้() → ข้อความไทยบอกผู้ใช้ว่าทำไมปุ่มถึงไม่ขึ้น (ไม่ติดขัดคืนค่าว่าง)
// ปุ่มที่หายไปเฉย ๆ โดยไม่บอกเหตุผล ทำให้ผู้ใช้คิดว่าระบบพัง
// ─────────────────────────────────────────────────────────────

// ── ดูใบลา ── พนักงานเห็นเฉพาะใบของตัวเอง · ผู้อนุมัติกับฝ่ายบุคคลเห็นทุกใบ
export function ดูใบลาได้(ผู้ใช้, ใบ) {
  return เป็นผู้ตัดสิน(ผู้ใช้) || เป็นเจ้าของใบ(ผู้ใช้, ใบ);
}

// ── เปลี่ยนสถานะ (อนุมัติ / ไม่อนุมัติ) ──
export function ตัดสินใบลาได้(ผู้ใช้, ใบ) {
  return เหตุผลที่ตัดสินไม่ได้(ผู้ใช้, ใบ) === "";
}

export function เหตุผลที่ตัดสินไม่ได้(ผู้ใช้, ใบ) {
  if (!เป็นผู้ตัดสิน(ผู้ใช้)) {
    return "เฉพาะผู้อนุมัติและฝ่ายบุคคลเท่านั้นที่เปลี่ยนสถานะใบลาได้";
  }
  // 🔒 กติกาที่ใช้กับทุกบทบาท — คนคนเดียวเป็นทั้งผู้ขอและผู้ตัดสินไม่ได้
  //    ต่อให้เป็น manager หรือ hr ก็อนุมัติใบของตัวเองไม่ได้
  if (เป็นเจ้าของใบ(ผู้ใช้, ใบ)) {
    return "อนุมัติใบลาของตัวเองไม่ได้ — ต้องให้ผู้อนุมัติคนอื่นเป็นคนตัดสิน";
  }
  if (ใบ && ใบ.status !== "รอพิจารณา") {
    return "ใบนี้พิจารณาแล้ว จึงเปลี่ยนสถานะต่อไม่ได้";
  }
  return "";
}

// ── ลบใบลา ── ลบได้เฉพาะใบของตัวเองที่ยังไม่ถูกตัดสิน
//    ผู้อนุมัติและฝ่ายบุคคลก็ลบใบของคนอื่นไม่ได้เหมือนกัน
export function ลบใบลาได้(ผู้ใช้, ใบ) {
  return เหตุผลที่ลบไม่ได้(ผู้ใช้, ใบ) === "";
}

export function เหตุผลที่ลบไม่ได้(ผู้ใช้, ใบ) {
  if (!เป็นเจ้าของใบ(ผู้ใช้, ใบ)) {
    return "ลบได้เฉพาะใบลาที่ตัวเองเป็นคนยื่นเท่านั้น";
  }
  if (ใบ && ใบ.status !== "รอพิจารณา") {
    return "ลบได้เฉพาะใบที่สถานะยังเป็น รอพิจารณา เท่านั้น";
  }
  return "";
}

// ── เขียนความเห็น ── เงื่อนไขเดียวกับการดูใบลา
//    พนักงานเขียนได้ในใบของตัวเอง · ผู้อนุมัติกับฝ่ายบุคคลเขียนได้ทุกใบ
//    (วันหลังถ้าสองเรื่องนี้แยกกัน ค่อยแก้ที่ฟังก์ชันนี้ ไม่ต้องไล่แก้ทุกหน้า)
export function เขียนความเห็นได้(ผู้ใช้, ใบ) {
  return ดูใบลาได้(ผู้ใช้, ใบ);
}

// ── จัดการประเภทการลา ── ฝ่ายบุคคลเท่านั้น
export function จัดการประเภทการลาได้(ผู้ใช้) {
  return เป็นฝ่ายบุคคล(ผู้ใช้);
}

// ─────────────────────────────────────────────────────────────
// ตัวช่วยสำหรับซ่อนเมนูและปุ่มบนหน้าจอ
// ─────────────────────────────────────────────────────────────

// ใช้กับสิ่งที่เขียนไว้ใน HTML ว่า data-เฉพาะบทบาท="hr" (หลายบทบาทคั่นด้วยเว้นวรรค)
// ยังไม่ล็อกอิน = ยังไม่รู้บทบาท ก็ถือว่าไม่ผ่าน ปล่อยให้ซ่อนไว้ตามเดิม
export function บทบาทตรงกับ(ผู้ใช้, รายชื่อบทบาท) {
  if (!ผู้ใช้ || !รายชื่อบทบาท) return false;
  return รายชื่อบทบาท.split(/\s+/).indexOf(ผู้ใช้.role) !== -1;
}
