// js/leave-types.js — หน้าที่ 4 จัดการประเภทการลา
// เพิ่ม แก้ ลบ ลงโฟลเดอร์ leaveTypes บน Firestore ของจริง
//
// 🔒 หน้านี้เป็นของฝ่ายบุคคล (hr) ตาม ACL.md
//    ผู้ขอลาและผู้อนุมัติเปิดเข้ามาได้ แต่เห็นเป็นรายการอ่านอย่างเดียว ไม่มีปุ่มจัดการ
//    (เมนู "ประเภทการลา" ถูกซ่อนไว้แล้วใน js/nav.js แต่พิมพ์ที่อยู่หน้าตรง ๆ ก็ยังเข้ามาได้
//     หน้าจึงต้องตรวจบทบาทของตัวเองซ้ำอีกชั้น ไม่พึ่งการซ่อนเมนูอย่างเดียว)
//    🛡️ ยามตัวจริงคือ firestore.rules — `allow write: if isHR()` ปฏิเสธคนอื่นให้อยู่แล้ว
//
// 🔑 จุดที่ต้องระวังที่สุดในไฟล์นี้
//    1. ต้องรอ (await) ให้เขียนสำเร็จก่อน ค่อยเปลี่ยนของบนหน้าจอ
//       เขียนไม่สำเร็จแล้วหน้าจอเปลี่ยนไปแล้ว = ผู้ใช้เข้าใจว่าบันทึกแล้ว ทั้งที่ในฐานยังเหมือนเดิม
//    2. ไม่ต้องใส่ช่อง id ลงไป เพราะบน Firestore id คือ "ชื่อไฟล์" ไม่ใช่ช่องข้อมูล
//    3. แก้ชื่อประเภทที่นี่ ไม่ได้ตามไปแก้ใบลาเก่า
//       ใบลาจดชื่อประเภทซ้ำไว้ในตัวเองตั้งแต่วันที่ยื่น (leaveTypeName ตาม CLAUDE.md ข้อ 1)
//       ซึ่งถูกแล้ว — ใบลาต้องบอกว่า "ตอนนั้นเรียกว่าอะไร" ไม่ใช่เปลี่ยนตามชื่อวันนี้
// ─────────────────────────────────────────────────────────────

import { db } from "./firebase-init.js";
import { ต้องล็อกอิน } from "./auth.js";
import { จัดการประเภทการลาได้ } from "./acl.js";
import { อ่านประเภทการลา, แปลข้อผิดพลาดประเภทการลา } from "./leave-types-data.js";
import {
  collection, addDoc, doc, updateDoc, deleteDoc
} from "https://www.gstatic.com/firebasejs/12.18.0/firebase-firestore.js";

(async function () {
  // ต้องรู้บทบาทก่อนวาดตาราง ไม่งั้นปุ่มลบจะแวบให้คนที่กดไม่ได้เห็นก่อนหายไป
  var ผู้ใช้ = await ต้องล็อกอิน();
  var แก้ไขได้ = จัดการประเภทการลาได้(ผู้ใช้);

  var ที่วางตาราง = document.getElementById("ตารางประเภท");
  var ช่องชื่อใหม่ = document.getElementById("ชื่อประเภทใหม่");
  var กล่องเตือน = document.getElementById("เตือนประเภท");
  var ปุ่มเพิ่ม = document.getElementById("ปุ่มเพิ่ม");

  var รายการ = [];

  // ปุ่มเพิ่มอยู่ในกล่องที่ซ่อนไว้สำหรับคนที่ไม่ใช่ฝ่ายบุคคล จึงผูกเฉพาะตอนที่มีสิทธิ์จริง
  if (แก้ไขได้ && ปุ่มเพิ่ม) {
    ปุ่มเพิ่ม.addEventListener("click", เพิ่มประเภท);
    ช่องชื่อใหม่.addEventListener("keydown", function (e) {
      if (e.key === "Enter") เพิ่มประเภท();      // พิมพ์เสร็จกด Enter ได้เลย ไม่ต้องย้ายมือไปเมาส์
    });
  }

  await โหลดรายการ();

  // ── อ่านรายการจากฐาน แล้ววาดใหม่ทั้งตาราง ──
  async function โหลดรายการ() {
    วาดกำลังโหลด();
    try {
      รายการ = await อ่านประเภทการลา();
      วาดตาราง();
    } catch (ข้อผิดพลาด) {
      // อ่านไม่ได้ ต้องบอกสาเหตุ ไม่ใช่ขึ้นตารางว่างแล้วให้ผู้ใช้เดาเอง
      // ตารางว่างกับอ่านไม่ได้คนละเรื่องกัน และแก้คนละทาง
      วาดข้อผิดพลาด(แปลข้อผิดพลาดประเภทการลา(ข้อผิดพลาด, "อ่าน"));
    }
  }

  // ── โครงร่างระหว่างรอฐานตอบ ──
  // ใช้โครงร่างแทนคำว่า "กำลังโหลด…" เพราะมันบอกล่วงหน้าว่ากำลังจะมีอะไรมา
  function วาดกำลังโหลด() {
    var html = "";
    for (var i = 0; i < 3; i++) {
      html += '<div class="field-row"><div class="skeleton sk-line" style="width:' +
              (38 + i * 9) + '%"></div></div>';
    }
    ที่วางตาราง.innerHTML = '<div class="field-list">' + html + "</div>";
  }

  function วาดข้อผิดพลาด(ข้อความ) {
    ที่วางตาราง.innerHTML =
      '<div class="alert alert-error" role="alert">' + window.ไอคอน("เตือน") +
      "<div>" + esc(ข้อความ) + "</div></div>";
  }

  function วาดตาราง() {
    if (รายการ.length === 0) {
      // สถานะว่างต้องสอนว่าทำอะไรต่อ ไม่ใช่แค่บอกว่าไม่มีข้อมูล
      ที่วางตาราง.innerHTML =
        '<div class="empty">' + window.ไอคอน("ป้าย") +
        "<h3>ยังไม่มีประเภทการลาในระบบ</h3>" +
        "<p>" + (แก้ไขได้
          ? "เพิ่มประเภทแรกได้จากกล่องข้างบน — ถ้ายังไม่มีประเภทการลาเลย จะไม่มีใครยื่นใบลาได้"
          : "ติดต่อฝ่ายบุคคลให้เพิ่มประเภทการลาก่อน จึงจะยื่นใบลาได้") +
        "</p></div>";
      return;
    }

    // ใช้ .field-list เหมือนหน้ารายละเอียดใบลา แทนตารางเปล่า ๆ
    // เพราะรายการนี้มีข้อมูลคอลัมน์เดียว ตารางจึงไม่ได้ช่วยอะไร แถมยังไม่มีสไตล์รองรับ
    var html = รายการ.map(function (ประเภท) {
      return '<div class="field-row" style="grid-template-columns:minmax(0,1fr) auto">' +
        '<span class="v">' + esc(ประเภท.name) + "</span>" +
        (แก้ไขได้
          ? '<span class="btn-row">' +
              '<button type="button" class="btn-ghost btn-sm" data-edit="' + esc(ประเภท.id) + '">' +
                window.ไอคอน("ดินสอ", "ico-sm") + "แก้ชื่อ</button>" +
              '<button type="button" class="btn-ghost btn-sm" data-del="' + esc(ประเภท.id) + '">' +
                window.ไอคอน("ถัง", "ico-sm") + "ลบ</button>" +
            "</span>"
          : "") +
        "</div>";
    }).join("");

    ที่วางตาราง.innerHTML = '<div class="field-list">' + html + "</div>";

    if (!แก้ไขได้) return;                      // ไม่มีปุ่มให้ผูกแล้ว

    ที่วางตาราง.querySelectorAll("[data-edit]").forEach(function (ปุ่ม) {
      ปุ่ม.addEventListener("click", function () { แก้ประเภท(ปุ่ม.dataset.edit); });
    });
    ที่วางตาราง.querySelectorAll("[data-del]").forEach(function (ปุ่ม) {
      ปุ่ม.addEventListener("click", function () { ลบประเภท(ปุ่ม.dataset.del); });
    });
  }

  // ── เพิ่มประเภทใหม่ลงโฟลเดอร์ leaveTypes ──
  async function เพิ่มประเภท() {
    var ชื่อ = ช่องชื่อใหม่.value.trim();

    if (!ชื่อ) {
      เตือน("พิมพ์ชื่อประเภทการลาก่อน จึงจะเพิ่มได้");
      ช่องชื่อใหม่.focus();
      return;
    }
    // ชื่อซ้ำทำให้คนยื่นใบลาเลือกผิดโดยไม่รู้ตัว เพราะสองบรรทัดหน้าตาเหมือนกันเป๊ะ
    if (มีชื่อนี้แล้ว(ชื่อ)) {
      เตือน("มีประเภท “" + ชื่อ + "” อยู่แล้ว");
      ช่องชื่อใหม่.focus();
      return;
    }
    ซ่อนเตือน();

    กำลังทำงาน(true, "กำลังเพิ่ม…");
    try {
      // addDoc = ให้ Firestore ตั้งชื่อไฟล์เอง · ไม่ส่งช่อง id ลงไป
      await addDoc(collection(db, "leaveTypes"), { name: ชื่อ });
      ช่องชื่อใหม่.value = "";                  // ล้างช่องก็ต่อเมื่อเขียนสำเร็จแล้วเท่านั้น
      await โหลดรายการ();
    } catch (ข้อผิดพลาด) {
      เตือน(แปลข้อผิดพลาดประเภทการลา(ข้อผิดพลาด, "แก้ไข"));
    } finally {
      กำลังทำงาน(false, "เพิ่มประเภทการลา");
    }
  }

  // ── แก้ชื่อ — แก้ช่อง name ช่องเดียว ──
  async function แก้ประเภท(id) {
    var ประเภท = รายการ.find(function (t) { return t.id === id; });
    if (!ประเภท) return;

    var ชื่อใหม่ = prompt("แก้ชื่อประเภทการลา", ประเภท.name);
    if (ชื่อใหม่ === null) return;              // กดยกเลิก
    ชื่อใหม่ = ชื่อใหม่.trim();

    if (!ชื่อใหม่) { เตือน("ชื่อประเภทการลาว่างเปล่าไม่ได้"); return; }
    if (ชื่อใหม่ === ประเภท.name) return;       // ไม่ได้เปลี่ยนอะไร ไม่ต้องแตะฐาน
    if (มีชื่อนี้แล้ว(ชื่อใหม่)) { เตือน("มีประเภท “" + ชื่อใหม่ + "” อยู่แล้ว"); return; }
    ซ่อนเตือน();

    ปิดปุ่มในตาราง(true);
    try {
      // 🔒 ส่งไปช่องเดียว — updateDoc จะไม่แตะช่องอื่นในไฟล์เลย
      await updateDoc(doc(db, "leaveTypes", id), { name: ชื่อใหม่ });
      await โหลดรายการ();
    } catch (ข้อผิดพลาด) {
      เตือน(แปลข้อผิดพลาดประเภทการลา(ข้อผิดพลาด, "แก้ไข"));
      ปิดปุ่มในตาราง(false);
    }
  }

  // ── ลบประเภท ──
  async function ลบประเภท(id) {
    var ประเภท = รายการ.find(function (t) { return t.id === id; });
    if (!ประเภท) return;

    // บอกให้ครบว่าลบแล้วเกิดอะไรขึ้นกับใบลาเก่า — คนกดจะได้ไม่ต้องเดา
    var ยืนยัน = confirm(
      'ลบประเภท "' + ประเภท.name + '" ออกจากฐานข้อมูลถาวร?\n\n' +
      "ใบลาเก่าที่เคยเลือกประเภทนี้จะยังแสดงชื่อเดิมได้ตามปกติ\n" +
      "เพราะใบลาจดชื่อประเภทซ้ำไว้ในตัวเองตั้งแต่วันที่ยื่น\n\n" +
      "แต่ต่อจากนี้จะไม่มีใครเลือกประเภทนี้ได้อีก"
    );
    if (!ยืนยัน) return;
    ซ่อนเตือน();

    ปิดปุ่มในตาราง(true);
    try {
      await deleteDoc(doc(db, "leaveTypes", id));
      await โหลดรายการ();
    } catch (ข้อผิดพลาด) {
      เตือน(แปลข้อผิดพลาดประเภทการลา(ข้อผิดพลาด, "แก้ไข"));
      ปิดปุ่มในตาราง(false);
    }
  }

  // เทียบชื่อแบบไม่สนตัวพิมพ์เล็กใหญ่และช่องว่างหัวท้าย
  function มีชื่อนี้แล้ว(ชื่อ) {
    var เทียบ = ชื่อ.toLowerCase();
    return รายการ.some(function (t) { return t.name.trim().toLowerCase() === เทียบ; });
  }

  // ระหว่างเขียนลงฐาน ปิดปุ่มไว้ กันกดซ้ำแล้วได้ประเภทซ้ำ 2 รายการ
  function กำลังทำงาน(อยู่, ข้อความ) {
    if (!ปุ่มเพิ่ม) return;
    ปุ่มเพิ่ม.disabled = อยู่;
    ปุ่มเพิ่ม.textContent = ข้อความ;
  }

  // ปิดทุกปุ่มในตาราง ไม่ใช่แค่ปุ่มที่กด — ไม่งั้นกดปุ่มอื่นซ้อนเข้ามาระหว่างรอได้
  function ปิดปุ่มในตาราง(ปิด) {
    ที่วางตาราง.querySelectorAll("button").forEach(function (ปุ่ม) {
      ปุ่ม.disabled = ปิด;
    });
  }

  function เตือน(ข้อความ) {
    if (!กล่องเตือน) { alert(ข้อความ); return; }   // คนที่ไม่ใช่ hr ไม่มีกล่องนี้บนหน้าจอ
    แสดงเตือน(กล่องเตือน, ข้อความ);
  }

  function ซ่อนเตือน() {
    if (กล่องเตือน) กล่องเตือน.classList.add("hidden");
  }
})();
