// ─────────────────────────────────────────────────────────────
// js/theme.js — จำว่าผู้ใช้อยากได้โหมดสว่างหรือโหมดมืด
//
// ⚠️ ไฟล์นี้ต้องโหลดใน <head> แบบ "ไม่ใส่ defer" เท่านั้น
//    เพราะมันต้องทำงานให้เสร็จ ก่อนเบราว์เซอร์วาดหน้าจอครั้งแรก
//    ถ้าใส่ defer หรือย้ายไปท้าย body ผู้ใช้โหมดมืดจะเห็นหน้าขาวแวบหนึ่งทุกครั้งที่เปลี่ยนหน้า
//    (ภาษาอังกฤษเรียกอาการนี้ว่า flash of unstyled content)
//
// 🔑 จุดที่ต้องระวังที่สุดในไฟล์นี้
//    1. โหมดที่ใช้จริงมี 2 ค่า — "สว่าง" กับ "มืด"
//       แต่สิ่งที่ "บันทึกไว้" มี 3 ค่า เพราะมี "ตามระบบ" ที่แปลว่ายังไม่เคยเลือกเอง
//    2. ไฟล์นี้ทำงานตอนที่ <body> ยังไม่เกิด ห้ามแตะ document.body เด็ดขาด
//       แตะได้แค่ document.documentElement (คือ <html>) กับของใน <head>
//    3. localStorage พังได้ (โหมดส่วนตัวบางเบราว์เซอร์ห้ามเขียน)
//       ทุกครั้งที่อ่านหรือเขียนจึงต้องมี try/catch ครอบเสมอ ห้ามปล่อยให้ทั้งหน้าพังเพราะเรื่องนี้
// ─────────────────────────────────────────────────────────────

(function () {
  var ชื่อช่องเก็บ = "leaveeasy:ธีม";

  // สีของแถบเบราว์เซอร์บนมือถือ — ต้องตรงกับ --พื้นแอป ของแต่ละโหมดใน css/style.css
  var สีแถบเบราว์เซอร์ = { สว่าง: "#f5f5f7", มืด: "#000000" };

  var ตัวเฝ้าค่าเครื่อง = window.matchMedia
    ? window.matchMedia("(prefers-color-scheme: dark)")
    : null;

  // ── เครื่องของผู้ใช้ตั้งไว้เป็นโหมดไหน ──
  function โหมดของเครื่อง() {
    return ตัวเฝ้าค่าเครื่อง && ตัวเฝ้าค่าเครื่อง.matches ? "มืด" : "สว่าง";
  }

  // ── ผู้ใช้เคยเลือกเองไว้ไหม ── คืน "สว่าง" · "มืด" · หรือ "ตามระบบ" ถ้ายังไม่เคยเลือก
  function ที่เลือกไว้() {
    try {
      var ค่า = localStorage.getItem(ชื่อช่องเก็บ);
      return (ค่า === "สว่าง" || ค่า === "มืด") ? ค่า : "ตามระบบ";
    } catch (e) {
      return "ตามระบบ";                       // เขียนอ่านไม่ได้ ก็ถือว่าไม่เคยเลือก
    }
  }

  // ── สรุปว่าตอนนี้ต้องแสดงผลเป็นโหมดไหน ──
  function โหมดที่ใช้อยู่() {
    var เลือกไว้ = ที่เลือกไว้();
    return เลือกไว้ === "ตามระบบ" ? โหมดของเครื่อง() : เลือกไว้;
  }

  // ── ติดป้ายบอก CSS ว่าตอนนี้โหมดไหน ──
  // css/style.css มีชุดสีของโหมดมืดอยู่ใต้ :root[data-theme="dark"]
  function ทาโหมด(โหมด) {
    document.documentElement.setAttribute("data-theme", โหมด === "มืด" ? "dark" : "light");
    ทาสีแถบเบราว์เซอร์(โหมด);
  }

  // ── แถบสถานะของเบราว์เซอร์มือถือ ──
  // ใน HTML เขียน <meta name="theme-color"> ไว้สองอัน ผูกกับค่าของเครื่อง
  // พอผู้ใช้เลือกเองสองอันนั้นจะผิดทันที จึงกวาดทิ้งแล้ววางอันเดียวที่ตรงกับโหมดจริง
  function ทาสีแถบเบราว์เซอร์(โหมด) {
    var หัว = document.head;
    if (!หัว) return;

    var เดิม = หัว.querySelectorAll('meta[name="theme-color"]');
    for (var i = 0; i < เดิม.length; i++) เดิม[i].parentNode.removeChild(เดิม[i]);

    var ป้ายใหม่ = document.createElement("meta");
    ป้ายใหม่.setAttribute("name", "theme-color");
    ป้ายใหม่.setAttribute("content", สีแถบเบราว์เซอร์[โหมด]);
    หัว.appendChild(ป้ายใหม่);
  }

  // ── สลับโหมด ── เรียกจากปุ่มในแถบเมนู (ดู js/nav.js)
  //
  //   จุดที่กด — { x, y } พิกัดบนหน้าจอที่ให้ออร่าเริ่มแผ่ออก
  //              ไม่ส่งมาก็ได้ จะเปลี่ยนทันทีแบบไม่มีออร่า
  function สลับโหมด(จุดที่กด) {
    var โหมดใหม่ = โหมดที่ใช้อยู่() === "มืด" ? "สว่าง" : "มืด";

    // 🔁 ถ้าโหมดใหม่บังเอิญตรงกับที่เครื่องตั้งไว้อยู่แล้ว ให้ลบค่าที่จำไว้ทิ้ง
    //    ผลคือกลับไปเป็น "ตามระบบ" เงียบ ๆ โดยที่ผู้ใช้ไม่ต้องรู้จักคำนี้เลย
    //    เขาจะได้ตามเครื่องต่อเองถ้าวันหลังเครื่องสลับโหมดตามเวลา
    //    ไม่ทำข้อนี้ = กดครั้งเดียวแล้วหลุดจากโหมดอัตโนมัติถาวร กลับเข้าไปไม่ได้อีกเลย
    try {
      if (โหมดใหม่ === โหมดของเครื่อง()) localStorage.removeItem(ชื่อช่องเก็บ);
      else localStorage.setItem(ชื่อช่องเก็บ, โหมดใหม่);
    } catch (e) {
      // จำไม่ได้ก็ไม่เป็นไร อย่างน้อยหน้านี้ต้องเปลี่ยนให้เห็น
    }

    เปลี่ยนโหมดแบบมีออร่า(โหมดใหม่, จุดที่กด);
    return โหมดใหม่;
  }

  // ─────────────────────────────────────────────────────────────
  // 🌗 ออร่าแผ่ออกจากปุ่ม
  //
  // สลับโหมดวูบเดียวทำให้ตาปรับไม่ทัน โดยเฉพาะขามืด → สว่างในห้องมืด
  // จึงให้โหมดใหม่ค่อย ๆ เปิดออกเป็นวงกลมจากจุดที่นิ้วแตะ
  // ตาได้ไล่ตามขอบวงที่ขยาย แทนที่จะโดนทั้งจอพร้อมกัน
  //
  // ใช้ View Transitions ของเบราว์เซอร์ — มันถ่ายภาพหน้าจอก่อนและหลังให้เอง
  // เราแค่บอกว่าภาพใหม่ให้เปิดออกเป็นวงกลมยังไง (ดู ::view-transition-* ใน css/style.css)
  //
  // 🔑 ทางที่ไม่มีออร่าต้องทำงานได้เสมอ
  //    เบราว์เซอร์เก่าที่ไม่มี startViewTransition · คนที่ตั้งค่าว่าไม่ชอบการเคลื่อนไหว
  //    ทั้งสองกลุ่มต้องได้โหมดใหม่ทันที ไม่ใช่กดแล้วเงียบ
  // ─────────────────────────────────────────────────────────────

  // รอบที่ยังขยายไม่จบ — เก็บไว้เพื่อสั่งจบทิ้งเมื่อผู้ใช้กดซ้อนเข้ามา
  var รอบที่ค้างอยู่ = null;

  function ชอบการเคลื่อนไหวน้อย() {
    return !!(window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches);
  }

  function เปลี่ยนโหมดแบบมีออร่า(โหมดใหม่, จุดที่กด) {
    var ทาแล้วบอก = function () {
      ทาโหมด(โหมดใหม่);
      ป่าวประกาศ(โหมดใหม่);
    };

    if (!document.startViewTransition || ชอบการเคลื่อนไหวน้อย() || !จุดที่กด) {
      ทาแล้วบอก();
      return;
    }

    // ── กดซ้อนระหว่างที่วงยังขยายไม่เสร็จ ──
    // 🔑 ต้องสั่งรอบเดิม "จบเดี๋ยวนี้" ก่อนเสมอ แล้วค่อยเริ่มรอบใหม่
    //
    //    เคยเขียนไว้ว่าให้เปลี่ยนสีทันทีแบบไม่มีออร่าแล้วปล่อยรอบเดิมวิ่งต่อ — ผิด
    //    เพราะภาพที่วงกำลังเปิดออกมานั้นถูกถ่ายไว้ตั้งแต่ตอนเริ่มรอบเดิม
    //    พอสีข้างใต้ถูกสลับกลางคัน คนดูจะเห็นวงขยายอยู่ดี ๆ แล้วสีกระตุกพลิก
    //    ดูเหมือนแอนิเมชันเล่นซ้อนกันสองรอบ ทั้งที่มันคือรอบเดียวที่ถูกแทรก
    //
    //    skipTransition() ทำให้รอบเดิมกระโดดไปอยู่ปลายทางทันที
    //    หน้าจอจึงนิ่งสนิทก่อนที่วงใหม่จะเริ่มนับหนึ่ง
    if (รอบที่ค้างอยู่) {
      try { รอบที่ค้างอยู่.skipTransition(); } catch (e) { /* รอบเดิมจบไปเองแล้ว */ }
      รอบที่ค้างอยู่ = null;
    }

    var การเปลี่ยน = document.startViewTransition(ทาแล้วบอก);
    รอบที่ค้างอยู่ = การเปลี่ยน;

    การเปลี่ยน.ready
      .then(function () {
        var x = จุดที่กด.x;
        var y = จุดที่กด.y;

        // วงต้องขยายจนคลุมทั้งจอ จึงวัดไปถึงมุมที่ไกลที่สุดจากจุดที่กด
        // วัดสั้นไปแม้แต่นิดเดียว จะเหลือมุมจอเป็นสีเก่าค้างอยู่ตอนจบ
        var รัศมี = Math.hypot(
          Math.max(x, window.innerWidth - x),
          Math.max(y, window.innerHeight - y)
        );

        document.documentElement.animate(
          {
            clipPath: [
              "circle(0px at " + x + "px " + y + "px)",
              "circle(" + รัศมี + "px at " + x + "px " + y + "px)"
            ]
          },
          {
            duration: 620,                    // ช้ากว่าจังหวะอื่นของระบบโดยตั้งใจ ตาจะได้ตามทัน
            easing: "cubic-bezier(.32, .72, 0, 1)",   // ตัวเดียวกับ --ผ่อน ใน css/style.css
            pseudoElement: "::view-transition-new(root)"
          }
        );
      })
      .catch(function () {
        // ตกแต่งไม่สำเร็จไม่ใช่เรื่องใหญ่ โหมดถูกเปลี่ยนไปแล้วตั้งแต่ ทาแล้วบอก()
      });

    การเปลี่ยน.finished
      .catch(function () {})
      .then(function () {
        // เคลียร์เฉพาะตอนที่ยังเป็นรอบของตัวเองอยู่
        // ถ้ามีรอบใหม่มาแทนที่ไปแล้ว ห้ามไปลบของคนอื่นทิ้ง
        if (รอบที่ค้างอยู่ === การเปลี่ยน) รอบที่ค้างอยู่ = null;
      });
  }

  // บอกคนที่สนใจว่าโหมดเปลี่ยนแล้ว — ปุ่มในแถบเมนูฟังอยู่ จะได้สลับไอคอนตาม
  function ป่าวประกาศ(โหมด) {
    document.dispatchEvent(new CustomEvent("ธีมเปลี่ยน", { detail: { โหมด: โหมด } }));
  }

  // ทาทันทีตั้งแต่บรรทัดนี้ ก่อนที่ <body> จะถูกอ่านด้วยซ้ำ
  ทาโหมด(โหมดที่ใช้อยู่());

  // เครื่องสลับโหมดเองระหว่างเปิดหน้าค้างไว้ (เช่นถึงเวลาพระอาทิตย์ตก)
  // ให้ตามไปด้วยเฉพาะตอนที่ผู้ใช้ยังไม่เคยเลือกเอง — ถ้าเขาเลือกไว้แล้ว ต้องเคารพสิ่งที่เขาเลือก
  if (ตัวเฝ้าค่าเครื่อง && ตัวเฝ้าค่าเครื่อง.addEventListener) {
    ตัวเฝ้าค่าเครื่อง.addEventListener("change", function () {
      if (ที่เลือกไว้() !== "ตามระบบ") return;
      ทาโหมด(โหมดของเครื่อง());
      ป่าวประกาศ(โหมดของเครื่อง());
    });
  }

  window.ธีม = {
    ใช้อยู่: โหมดที่ใช้อยู่,
    เลือกไว้: ที่เลือกไว้,
    สลับ: สลับโหมด
  };
})();
