  // ── เปลี่ยนสถานะ แล้วบันทึกลงฐานข้อมูลจริง ──
  async function เปลี่ยนสถานะ(สถานะใหม่) {
    // ตรวจสิทธิ์ซ้ำก่อนแตะฐานเสมอ — สถานะของใบอาจเปลี่ยนไปแล้วตั้งแต่ตอนวาดปุ่ม
    if (!ตัดสินใบลาได้(ผู้ใช้, ใบ)) {
      แจ้งผล = { ชนิด: "error", ข้อความ: เหตุผลที่ตัดสินไม่ได้(ผู้ใช้, ใบ) };
      วาดใบลา();
      return;
    }

    // กฎ: จะไม่อนุมัติได้ ต้องมีความเห็นอย่างน้อย 1 รายการก่อน
    // นับจาก ความเห็น ซึ่งตอนนี้ตรงกับของในฐานข้อมูลเสมอ เพราะความเห็นถูกบันทึกจริงแล้ว
    if (สถานะใหม่ === "ไม่อนุมัติ" && ความเห็น.length === 0) {
      แจ้งผล = { ชนิด: "error", ข้อความ: "ต้องเขียนความเห็นอย่างน้อย 1 รายการก่อน จึงจะกดไม่อนุมัติได้" };
      วาดใบลา();
      return;
    }

    ปิดปุ่มในกล่องใบลา(true);
    try {
      // 🔒 ส่งไปช่องเดียว — updateDoc จะไม่แตะช่องอื่นในไฟล์เลย
      await updateDoc(doc(db, "leaveRequests", ใบ.id), { status: สถานะใหม่ });

      ใบ.status = สถานะใหม่;                  // เขียนสำเร็จแล้วเท่านั้นถึงเปลี่ยนของบนหน้าจอ
      แจ้งผล = { ชนิด: "ok", ข้อความ: "บันทึกสถานะ " + สถานะใหม่ + " ลงฐานข้อมูลแล้ว" };
      วาดใบลา();
    } catch (ข้อผิดพลาด) {
      // สถานะบนหน้าจอต้องคงเดิม ปุ่มต้องกลับมากดได้
      แจ้งผล = { ชนิด: "error", ข้อความ: แปลข้อผิดพลาดการเขียน(ข้อผิดพลาด) };
      วาดใบลา();
    }
  }

  // ระหว่างคุยกับฐานข้อมูล ปิดปุ่มทุกปุ่มในกล่องใบลา
  // ถ้าปิดแค่ปุ่มที่กด ผู้ใช้ยังกดปุ่มอื่นซ้อนเข้ามาระหว่างรอได้
