// 🔑 จุดที่ต้องระวังที่สุดในไฟล์นี้
//    1. เปลี่ยนสถานะต้องใช้ updateDoc ไม่ใช่ setDoc
//       updateDoc แก้เฉพาะช่องที่ระบุ · setDoc เขียนทับทั้งไฟล์
//       ถ้าใช้ setDoc แล้วส่งไปแค่ status อีก 11 ช่องจะหายทันที
//    2. เขียนไม่สำเร็จ ห้ามเปลี่ยนสิ่งที่เห็นบนหน้าจอ
//       ไม่งั้นผู้ใช้จะเข้าใจว่าอนุมัติไปแล้ว ทั้งที่ในฐานยังเป็น รอพิจารณา
//    3. บน Firestore id คือ "ชื่อไฟล์" ไม่ใช่ช่องข้อมูลข้างใน
//       ตอนอ่านต้องแปะชื่อไฟล์กลับเป็นช่อง id เอง · ตอนเขียนต้องไม่ส่งช่อง id ลงไป
//    4. ลบใบลา ต้องลบโฟลเดอร์ย่อย approvals ด้วยตัวเองเสมอ
//       Firestore ไม่ลบโฟลเดอร์ย่อยตามให้ ความเห็นจะค้างเป็นข้อมูลกำพร้าที่มองไม่เห็น
//       และถ้าวันหลังมีไฟล์ชื่อเดิมเกิดขึ้นอีก (เช่น กดใส่ข้อมูลตัวอย่างซ้ำ)
//       ความเห็นเก่าจะโผล่กลับมาแปะอยู่ในใบใหม่
// ─────────────────────────────────────────────────────────────

import { db } from "./firebase-init.js";
import { ต้องล็อกอิน } from "./auth.js";
import {
  ดูใบลาได้, ตัดสินใบลาได้, เหตุผลที่ตัดสินไม่ได้,
  ลบใบลาได้, เหตุผลที่ลบไม่ได้, เขียนความเห็นได้, เป็นเจ้าของใบ
} from "./acl.js";
import {
  doc, getDoc, updateDoc, collection, getDocs, addDoc, writeBatch
} from "https://www.gstatic.com/firebasejs/12.18.0/firebase-firestore.js";

(async function () {
  // ยังไม่ล็อกอินก็เด้งไปหน้าเข้าสู่ระบบ — ต้องรู้ว่าใครอ่านอยู่ เพราะคนนี้คือผู้เขียนความเห็น
  var ผู้ใช้ = await ต้องล็อกอิน();
  var รหัสใบลา = ค่าจากURL("id");
  var กล่องใบลา = document.getElementById("กล่องใบลา");
  var กล่องความเห็น = document.getElementById("กล่องความเห็น");

  var ใบ, ความเห็น;

  // ข้อความแจ้งผลของการกดปุ่มสถานะ · เก็บไว้ในตัวแปรเพราะ วาดใบลา() เขียนทับทั้งกล่อง
  // ถ้าแปะไว้ในหน้าจอตรง ๆ การวาดรอบถัดไปจะลบข้อความทิ้งก่อนผู้ใช้ทันอ่าน
  var แจ้งผล = null;

  try {
    ใบ = await อ่านใบลา(รหัสใบลา);
  } catch (ข้อผิดพลาด) {
    แสดงข้อผิดพลาด(ข้อผิดพลาด);
    return;                                  // ต่อฐานไม่ได้ ต้องไม่ขึ้น "ไม่พบใบขอลา"
  }

  if (!ใบ) {
    กล่องใบลา.innerHTML =
      '<div class="empty">' + window.ไอคอน("กล่องว่าง") +
      "<h3>ไม่พบใบขอลาที่ต้องการ</h3>" +
      "<p>ใบนี้อาจถูกลบไปแล้ว หรือลิงก์ที่เปิดมาไม่ถูกต้อง</p>" +
      '<div class="btn-row"><a class="btn btn-ghost" href="leave-requests.html">กลับไปหน้ารายการ</a></div></div>';
    return;
  }

  // ── ด่านตรวจสิทธิ์การดู ── ผู้ขอลาเปิดดูได้เฉพาะใบที่ตัวเองยื่น
  // การซ่อนแถวในหน้ารายการอย่างเดียวไม่พอ เพราะพิมพ์ ?id= เข้ามาตรง ๆ ก็ถึงหน้านี้ได้
  // 🔒 นี่คือการปิดหน้าจอเท่านั้น — ข้อมูลถูกอ่านจากฐานมาแล้วก่อนถึงบรรทัดนี้
  //    กันการอ่านจริงต้องไปเขียนเงื่อนไขใน firestore.rules
  if (!ดูใบลาได้(ผู้ใช้, ใบ)) {
    กล่องใบลา.innerHTML =
      '<div class="empty">' + window.ไอคอน("ล็อก") +
      "<h3>ใบลาใบนี้ไม่ใช่ใบที่คุณยื่น</h3>" +
      "<p>ผู้ขอลาเปิดดูได้เฉพาะใบลาของตัวเองเท่านั้น</p>" +
      '<div class="btn-row"><a class="btn btn-ghost" href="leave-requests.html">กลับไปหน้ารายการ</a></div></div>';
    return;                                  // ไม่อ่านความเห็น ไม่เปิดกล่องความเห็น
  }

  try {
    ความเห็น = await อ่านความเห็น(ใบ.id);
  } catch (ข้อผิดพลาด) {
    ความเห็น = [];                            // อ่านความเห็นไม่ได้ ก็ยังให้ดูใบลาต่อได้
  }

  วาดใบลา();
  วาดความเห็น();

  // ผู้ขอลาเขียนความเห็นได้เฉพาะในใบของตัวเอง · ผู้อนุมัติกับฝ่ายบุคคลเขียนได้ทุกใบ
  if (เขียนความเห็นได้(ผู้ใช้, ใบ)) {
    กล่องความเห็น.classList.remove("hidden");
    document.getElementById("ปุ่มส่งความเห็น").addEventListener("click", ส่งความเห็น);
  }

  // ปุ่มในหน้าต่างยืนยัน อยู่นอกกล่องใบลาที่ถูกวาดใหม่เรื่อย ๆ จึงผูกครั้งเดียวพอ
  var หน้าต่างลบ = document.getElementById("หน้าต่างยืนยันลบ");
  document.getElementById("ปุ่มยกเลิกลบ").addEventListener("click", function () {
    หน้าต่างลบ.close();                      // ยกเลิก = ปิดหน้าต่างเฉย ๆ ไม่แตะฐานข้อมูลเลย
  });
  document.getElementById("ปุ่มยืนยันลบ").addEventListener("click", ลบใบลา);

  // ── อ่านใบลา 1 ใบจากโฟลเดอร์ leaveRequests ──
  async function อ่านใบลา(รหัส) {
    if (!รหัส) return null;

    var ไฟล์ = await getDoc(doc(db, "leaveRequests", รหัส));
    if (!ไฟล์.exists()) return null;

    // ไฟล์.id = ชื่อไฟล์ (เช่น "lr001") · ไฟล์.data() = ช่องข้อมูลข้างใน
    return Object.assign({ id: ไฟล์.id }, ไฟล์.data());
  }

  // ── อ่านความเห็นจากโฟลเดอร์ย่อย approvals ที่ซ้อนอยู่ในใบลาใบนี้ ──
  // ไม่ต้องกรองด้วย requestId เหมือนตอนใช้ข้อมูลปลอม เพราะโฟลเดอร์ย่อยนี้
  // เป็นของใบลาใบนี้อยู่แล้วโดยโครงสร้าง
  async function อ่านความเห็น(รหัส) {
    var ผล = await getDocs(collection(db, "leaveRequests", รหัส, "approvals"));
    return ผล.docs.map(function (ไฟล์) {
      return Object.assign({ id: ไฟล์.id }, ไฟล์.data());
    });
  }

  // ── ต่อฐานข้อมูลไม่ได้ ต้องบอกสาเหตุ ไม่ใช่ค้างที่ "กำลังโหลด…" ตลอดไป ──
  function แสดงข้อผิดพลาด(e) {
    var รหัส = (e && e.code) || "";
    var สาเหตุ;

    if (รหัส === "permission-denied") {
      สาเหตุ = "Firestore ปฏิเสธการอ่าน — บัญชีนี้ไม่มีสิทธิ์อ่านข้อมูลชุดนี้ตามกฎใน firestore.rules " +
               "(ผู้ขอลาอ่านได้เฉพาะใบลาของตัวเอง) ถ้าเพิ่งแก้กฎ อย่าลืมกด Publish ที่ Firebase Console";
    } else if (รหัส === "unavailable") {
      สาเหตุ = "ต่อฐานข้อมูลไม่ได้ — ตรวจว่าเครื่องต่อเน็ตอยู่ แล้วกด F5 อีกครั้ง";
    } else if (รหัส === "not-found") {
      สาเหตุ = "ไม่พบฐานข้อมูลของโปรเจกต์นี้ — ตรวจค่าใน js/firebase-init.js";
    } else {
      สาเหตุ = "อ่านข้อมูลไม่สำเร็จ — " + ((e && e.message) || String(e));
    }

    กล่องใบลา.innerHTML =
      '<div style="padding:20px"><div class="alert alert-error" style="margin:0">' +
      window.ไอคอน("เตือน") + "<div>" + esc(สาเหตุ) + "</div></div></div>";
  }

  // ── แปลข้อผิดพลาดตอน "เขียน" ให้อ่านรู้เรื่อง ──
  function แปลข้อผิดพลาดการเขียน(e) {
    var รหัส = (e && e.code) || "";

    if (รหัส === "permission-denied") {
      return "Firestore ปฏิเสธการเขียน — บัญชีนี้ไม่มีสิทธิ์ทำรายการนี้ตามกฎใน firestore.rules " +
             "(เช่น ตัดสินใบลาของตัวเอง หรือแก้ใบที่พิจารณาไปแล้ว) ถ้าเพิ่งแก้กฎ อย่าลืมกด Publish ที่ Firebase Console";
    }
    if (รหัส === "unavailable" || รหัส === "failed-precondition") {
      return "ต่อฐานข้อมูลไม่ได้ — ตรวจว่าเครื่องต่อเน็ตอยู่ แล้วลองอีกครั้ง";
    }
    if (รหัส === "not-found") {
      return "ไม่พบใบขอลาใบนี้ในฐานข้อมูลแล้ว — อาจถูกลบไประหว่างที่เปิดหน้านี้ค้างไว้ กด F5 เพื่อดูสถานะล่าสุด";
    }
    return "บันทึกไม่สำเร็จ — " + ((e && e.message) || String(e));
  }

  // ── วาดข้อมูลใบลาลงหน้าจอ ──
  //
  // แบ่งเป็นสามส่วนตามลำดับที่คนอ่านจริง
  //    1. หัวใบ   — หัวข้อ สถานะ ช่วงวันลา · สามอย่างนี้ตอบคำถามแรกของทุกคนได้ทันที
  //    2. รายการข้อมูล — รายละเอียดที่เหลือ เรียงเป็นคู่ "หัวข้อ : ค่า"
  //    3. แถบตัดสินใจ — ปุ่มทั้งหมดรวมอยู่ท้ายสุดที่เดียว พื้นต่างสีเล็กน้อยให้รู้ว่า "ตรงนี้คือที่ลงมือ"
  function วาดใบลา() {
    var วัน = จำนวนวันลา(ใบ.startDate, ใบ.endDate);

    var html =
      '<div class="request-head">' +
        '<div class="top"><h2>' + esc(ใบ.title) + "</h2>" + ป้ายสถานะ(ใบ.status) + "</div>" +
        '<div class="when">' + window.ไอคอน("ปฏิทิน") +
          "<span>" + ช่วงวันลา(ใบ.startDate, ใบ.endDate) + "</span>" +
          (วัน ? '<span class="days">· ' + วัน + " วัน</span>" : "") +
        "</div>" +
      "</div>";

    var แถว = [
      ["เหตุผลการลา", '<span class="v multiline">' + esc(ใบ.reason) + "</span>"],
      ["ประเภทการลา", esc(ใบ.leaveTypeName)],
      ["ผู้ขอลา", คนหนึ่งคน(ใบ.requesterName)],
      ["ผู้อนุมัติ", ใบ.approverName
        ? คนหนึ่งคน(ใบ.approverName)
        : '<span style="color:var(--ตัวอักษรจาง)">ยังไม่ได้กำหนดผู้อนุมัติ</span>'],
      ["วันที่ยื่น", วันที่ไทย(ใบ.createdAt)]
    ];

    html += '<div class="field-list">' + แถว.map(function (r) {
      var ค่า = r[1].indexOf('class="v') === -1 ? '<span class="v">' + r[1] + "</span>" : r[1];
      return '<div class="field-row"><span class="k">' + r[0] + "</span>" + ค่า + "</div>";
    }).join("") + "</div>";

    // ── ปุ่มขึ้นตามตารางสิทธิ์ใน ACL.md ── ถามจาก js/acl.js ที่เดียว ไม่เขียนเงื่อนไขเองตรงนี้
    // เหตุผลที่กดไม่ได้เอามาแสดงเป็นคำอธิบายด้วย ปุ่มที่หายไปเฉย ๆ ทำให้ผู้ใช้คิดว่าระบบพัง
    var ตัดสินได้ = ตัดสินใบลาได้(ผู้ใช้, ใบ);
    var ลบได้ = ลบใบลาได้(ผู้ใช้, ใบ);
    var เจ้าของ = เป็นเจ้าของใบ(ผู้ใช้, ใบ);

    var ปุ่ม = "";

    // ปุ่มอนุมัติ / ไม่อนุมัติ — เฉพาะผู้อนุมัติกับฝ่ายบุคคล ที่ไม่ใช่เจ้าของใบ และใบยังรอพิจารณา
    if (ตัดสินได้) {
      ปุ่ม += '<button type="button" class="btn-ok" id="ปุ่มอนุมัติ">' +
              window.ไอคอน("บันทึก", "ico-sm") + "อนุมัติ</button>" +
              '<button type="button" class="btn-danger" id="ปุ่มไม่อนุมัติ">' +
              window.ไอคอน("ผิด", "ico-sm") + "ไม่อนุมัติ</button>";
    }

    // ปุ่มลบดันไปชิดขวาสุด ห่างจากปุ่มพิจารณา จะได้ไม่กดพลาด
    // ขึ้นเฉพาะเจ้าของใบ — คนอื่นลบใบนี้ไม่ได้อยู่แล้ว ไม่ต้องเห็นปุ่มให้สับสน
    // เจ้าของใบที่พิจารณาแล้วยังเห็นปุ่มอยู่ แต่กดไม่ได้ — ให้รู้ว่ามีปุ่มนี้ แค่ใช้กับใบนี้ไม่ได้แล้ว
    if (เจ้าของ) {
      ปุ่ม += '<span style="flex:1 1 auto"></span>' +
              '<button type="button" class="btn-ghost" id="ปุ่มลบ"' + (ลบได้ ? "" : " disabled") + ">" +
              window.ไอคอน("ถัง", "ico-sm") + "ลบใบลา</button>";
    }

    // คำอธิบายว่าทำไมกดไม่ได้ ต้องอยู่ใต้ปุ่มเสมอ ไม่ใช่ให้ปุ่มหายไปเฉย ๆ
    var คำอธิบาย = "";
    if (ตัดสินได้) {
      คำอธิบาย = "กดแล้วสถานะจะถูกบันทึกลงฐานข้อมูลทันที และเปลี่ยนกลับไม่ได้";
    } else {
      คำอธิบาย = เหตุผลที่ตัดสินไม่ได้(ผู้ใช้, ใบ);
    }
    if (เจ้าของ && !ลบได้) {
      คำอธิบาย += " · " + เหตุผลที่ลบไม่ได้(ผู้ใช้, ใบ);
    }

    html += '<div class="decide">';
    if (แจ้งผล) {
      html += '<div class="alert alert-' + แจ้งผล.ชนิด + '" role="status">' +
              window.ไอคอน(แจ้งผล.ชนิด === "ok" ? "ถูก" : "เตือน") +
              "<div>" + esc(แจ้งผล.ข้อความ) + "</div></div>";
    }
    if (ปุ่ม) html += '<div class="btn-row">' + ปุ่ม + "</div>";
    html += '<p class="hint">' + window.ไอคอน(ตัดสินได้ ? "ข้อมูล" : "ล็อก", "ico-sm") + " " +
            esc(คำอธิบาย) + "</p></div>";

    กล่องใบลา.innerHTML = html;

    if (ตัดสินได้) {
      document.getElementById("ปุ่มอนุมัติ").addEventListener("click", function () { เปลี่ยนสถานะ("อนุมัติ"); });
      document.getElementById("ปุ่มไม่อนุมัติ").addEventListener("click", function () { เปลี่ยนสถานะ("ไม่อนุมัติ"); });
    }
    if (ลบได้) {
      document.getElementById("ปุ่มลบ").addEventListener("click", ถามยืนยันก่อนลบ);
    }
  }

  // ── เปลี่ยนสถานะ แล้วบันทึกลงฐานข้อมูลจริง ──
  async function เปลี่ยนสถานะ(สถานะใหม่) {
    // ตรวจสิทธิ์ซ้ำก่อนแตะฐานเสมอ — สถานะของใบอาจเปลี่ยนไปแล้วตั้งแต่ตอนวาดปุ่ม
    if (!ตัดสินใบลาได้(ผู้ใช้, ใบ)) {
      แจ้งผล = { ชนิด: "error", ข้อความ: เหตุผลที่ตัดสินไม่ได้(ผู้ใช้, ใบ) };
      วาดใบลา();
      return;
    }

    // กฎ: จะไม่อนุมัติได้ ต้องมีความเห็นอย่างน้อย 1 รายการก่อน
    // นับจาก ความเห็น ซึ่งตอนนี้ตรงกับของในฐานข้อมูลเสมอ เพราะความเห็นถูกบันทึกจริงแล้ว
    if (สถานะใหม่ === "ไม่อนุมัติ" && ความเห็น.length === 0) {
      แจ้งผล = { ชนิด: "error", ข้อความ: "ต้องเขียนความเห็นอย่างน้อย 1 รายการก่อน จึงจะกดไม่อนุมัติได้" };
      วาดใบลา();
      return;
    }

    ปิดปุ่มในกล่องใบลา(true);
    try {
      // 🔒 ส่งไปช่องเดียว — updateDoc จะไม่แตะช่องอื่นในไฟล์เลย
      await updateDoc(doc(db, "leaveRequests", ใบ.id), { status: สถานะใหม่ });

      ใบ.status = สถานะใหม่;                  // เขียนสำเร็จแล้วเท่านั้นถึงเปลี่ยนของบนหน้าจอ
      แจ้งผล = { ชนิด: "ok", ข้อความ: "บันทึกสถานะ " + สถานะใหม่ + " ลงฐานข้อมูลแล้ว" };
      วาดใบลา();
    } catch (ข้อผิดพลาด) {
      // สถานะบนหน้าจอต้องคงเดิม ปุ่มต้องกลับมากดได้
      แจ้งผล = { ชนิด: "error", ข้อความ: แปลข้อผิดพลาดการเขียน(ข้อผิดพลาด) };
      วาดใบลา();
    }
  }

  // ระหว่างคุยกับฐานข้อมูล ปิดปุ่มทุกปุ่มในกล่องใบลา
  // ถ้าปิดแค่ปุ่มที่กด ผู้ใช้ยังกดปุ่มอื่นซ้อนเข้ามาระหว่างรอได้
  function ปิดปุ่มในกล่องใบลา(ปิด) {
    กล่องใบลา.querySelectorAll("button").forEach(function (ปุ่ม) {
      ปุ่ม.disabled = ปิด;
    });
  }

  // ── กดปุ่มลบ = เปิดหน้าต่างถาม ยังไม่ลบอะไรทั้งสิ้น ──
  function ถามยืนยันก่อนลบ() {
    // บอกชื่อใบที่กำลังจะหายไป กันลบผิดใบตอนเปิดหลายแท็บ
    document.getElementById("ข้อความยืนยันลบ").textContent =
      "จะลบใบลา “" + ใบ.title + "” ออกจากฐานข้อมูลถาวร";
    หน้าต่างลบ.showModal();
  }

  // ── ลบจริง · ทำงานก็ต่อเมื่อผู้ใช้กดยืนยันในหน้าต่างแล้วเท่านั้น ──
  async function ลบใบลา() {
    หน้าต่างลบ.close();

    // ตรวจสิทธิ์ซ้ำก่อนลบจริง — หน้าต่างยืนยันอาจถูกเปิดค้างไว้ข้ามการเปลี่ยนสถานะ
    if (!ลบใบลาได้(ผู้ใช้, ใบ)) {
      แจ้งผล = { ชนิด: "error", ข้อความ: เหตุผลที่ลบไม่ได้(ผู้ใช้, ใบ) };
      วาดใบลา();
      return;
    }

    ปิดปุ่มในกล่องใบลา(true);

    var ปุ่มลบ = document.getElementById("ปุ่มลบ");
    if (ปุ่มลบ) ปุ่มลบ.textContent = "กำลังลบ…";

    try {
      // อ่านความเห็นสด ๆ จากฐานอีกรอบ ไม่ใช้ตัวแปรในหน่วยความจำ
      // เพราะอาจมีคนเพิ่มความเห็นเข้ามาหลังจากเราเปิดหน้านี้ค้างไว้
      var ความเห็นในฐาน = await getDocs(collection(db, "leaveRequests", ใบ.id, "approvals"));

      // 🔒 ลบความเห็นทุกไฟล์ + ไฟล์ใบลา พร้อมกันในชุดเดียว
      //    สำเร็จทั้งหมด หรือไม่สำเร็จเลย — ไม่มีสภาพลบครึ่ง ๆ กลาง ๆ ตอนเน็ตหลุด
      var ชุดลบ = writeBatch(db);
      ความเห็นในฐาน.forEach(function (ไฟล์) { ชุดลบ.delete(ไฟล์.ref); });
      ชุดลบ.delete(doc(db, "leaveRequests", ใบ.id));
      await ชุดลบ.commit();

      location.href = "leave-requests.html";  // ลบสำเร็จแล้วเท่านั้นถึงเปลี่ยนหน้า
    } catch (ข้อผิดพลาด) {
      // ลบไม่สำเร็จ ใบลายังอยู่ครบ ต้องไม่พาออกจากหน้านี้
      แจ้งผล = { ชนิด: "error", ข้อความ: แปลข้อผิดพลาดการเขียน(ข้อผิดพลาด) };
      วาดใบลา();
    }
  }

  // ชื่อคนพร้อมวงกลมอักษรย่อ — ใช้ให้เหมือนกันทั้งในรายการข้อมูลและในเส้นเวลาความเห็น
  function คนหนึ่งคน(ชื่อ) {
    return '<span class="v person">' + วงอักษรย่อ(ชื่อ) + "<span>" + esc(ชื่อ || "—") + "</span></span>";
  }

  // ── รายการความเห็น เรียงจากเก่าไปใหม่ ──
  // วาดเป็นเส้นเวลา มีเส้นแนวตั้งลากเชื่อมแต่ละความเห็น
  // เพราะสิ่งที่ต้องอ่านออกคือ "ใครพูดอะไรก่อนหลัง" ไม่ใช่แค่กองข้อความ
  function วาดความเห็น() {
    var ที่วาง = document.getElementById("รายการความเห็น");

    if (ความเห็น.length === 0) {
      ที่วาง.innerHTML =
        '<p class="hint" style="margin:0">' + window.ไอคอน("ความเห็น", "ico-sm") +
        " ยังไม่มีความเห็นในใบนี้ — เขียนความเห็นแรกได้ในช่องข้างล่าง</p>";
      return;
    }

    ที่วาง.innerHTML = ความเห็น
      .slice()
      .sort(function (a, b) { return a.createdAt < b.createdAt ? -1 : 1; })
      .map(function (c) {
        return '<div class="note">' + วงอักษรย่อ(c.authorName) +
          '<div><div class="meta"><b>' + esc(c.authorName) + "</b>" +
          "<time>" + วันที่ไทย(c.createdAt) + "</time></div>" +
          '<div class="body">' + esc(c.message) + "</div></div></div>";
      }).join("");
  }

  // ── ส่งความเห็นใหม่ลงโฟลเดอร์ย่อย approvals ของใบนี้ ──
  async function ส่งความเห็น() {
    var ช่อง = document.getElementById("ข้อความความเห็น");
    var เตือน = document.getElementById("เตือนความเห็น");
    var ปุ่ม = document.getElementById("ปุ่มส่งความเห็น");
    var ข้อความ = ช่อง.value.trim();

    if (!ข้อความ) {
      แสดงเตือน(เตือน, "พิมพ์ข้อความก่อน จึงจะส่งความเห็นได้");
      เตือน.classList.remove("hidden");
      return;
    }
    เตือน.classList.add("hidden");

    // ผู้เขียนคือคนที่ล็อกอินอยู่ตอนนี้ — จด authorName ซ้ำไว้ด้วยเสมอ เพราะ Firestore ไม่มี JOIN
    // ไม่ใส่ช่อง id และไม่ใส่ requestId เพราะความเห็นนี้ซ้อนอยู่ในใบลาใบนั้นแล้วโดยโครงสร้าง
    var ความเห็นใหม่ = {
      authorId: ผู้ใช้.uid, authorName: ผู้ใช้.name,
      message: ข้อความ,
      createdAt: เวลาตอนนี้()
    };

    ปุ่ม.disabled = true;
    ปุ่ม.textContent = "กำลังส่ง…";
    try {
      var ไฟล์ = await addDoc(collection(db, "leaveRequests", ใบ.id, "approvals"), ความเห็นใหม่);

      // แปะชื่อไฟล์ที่ Firestore ตั้งให้ กลับเข้ามาเป็นช่อง id เหมือนตอนอ่านจากฐาน
      ความเห็น.push(Object.assign({ id: ไฟล์.id }, ความเห็นใหม่));
      ช่อง.value = "";                        // ล้างช่องก็ต่อเมื่อส่งสำเร็จแล้วเท่านั้น
      วาดความเห็น();
    } catch (ข้อผิดพลาด) {
      // ส่งไม่สำเร็จ ข้อความที่พิมพ์ไว้ต้องยังอยู่ให้กดส่งซ้ำได้
      แสดงเตือน(เตือน, แปลข้อผิดพลาดการเขียน(ข้อผิดพลาด));
      เตือน.classList.remove("hidden");
    }
    ปุ่ม.disabled = false;
    ปุ่ม.textContent = "ส่งความเห็น";
  }
})();
