  async function สรุปด้วยเอไอ() {
    // ตรวจสิทธิ์ซ้ำก่อนแตะฐานเสมอ — หน้านี้อาจถูกเปิดค้างไว้ข้ามการเปลี่ยนบทบาท
    if (!สั่งสรุปได้()) {
      เอไอ.ปัญหา = "เฉพาะผู้อนุมัติและฝ่ายบุคคลที่ไม่ใช่เจ้าของใบเท่านั้นที่สั่งให้ AI สรุปได้";
      วาดใบลา();
      return;
    }

    if (!มีคีย์ไหม()) {
      เอไอ.ปัญหา = แปลข้อผิดพลาดAI({ รหัส: "ไม่มีคีย์" });
      วาดใบลา();
      return;
    }

    เอไอ = { กำลังทำ: true, ขั้นที่: "ขั้นที่ 1/3 · กำลังอ่านใบลาและความเห็นทั้งหมด…", ปัญหา: "" };
    วาดใบลา();

    // ใช้บอกตอนพังว่า "พังก่อนหรือหลัง AI ตอบ" — ทั้ง 3 ขั้นอยู่ใน try เดียวกัน
    // ถ้าไม่จำไว้ ข้อความตอนอ่านความเห็นไม่สำเร็จจะไปโทษการบันทึก ทั้งที่ AI ยังไม่ได้ทำงานเลย
    var เอไอตอบแล้ว = false;

    try {
      // ── ขั้นที่ 1 · อ่าน ──
      // อ่านความเห็นสด ๆ จากฐานอีกรอบ ไม่ใช้ตัวแปรในหน่วยความจำ
      // เพราะหัวหน้าอาจเปิดหน้านี้ค้างไว้ตั้งแต่ก่อนมีคนเขียนความเห็นเพิ่ม
      // สรุปที่ตกความเห็นล่าสุดไป อันตรายกว่าไม่มีสรุปเลย
      var ความเห็นสด = await อ่านความเห็น(ใบ.id);

      // ── ขั้นที่ 2 · สรุป ──
      เอไอ.ขั้นที่ = "ขั้นที่ 2/3 · กำลังให้ AI เขียนสรุป…";
      วาดใบลา();

      var ข้อความที่ส่งไป = เรียบเรียงใบลาให้เอไอ(ความเห็นสด);
      var สรุป = await เรียกAI(ข้อความระบบสรุป(), ข้อความที่ส่งไป);
      เอไอตอบแล้ว = true;

      // ── ขั้นที่ 3 · เขียนกลับลงฐาน ──
      เอไอ.ขั้นที่ = "ขั้นที่ 3/3 · กำลังบันทึกสรุปและบันทึกการเรียกลงฐานข้อมูล…";
      วาดใบลา();

      // 🔒 ส่งไปช่องเดียวเหมือนตอนเปลี่ยนสถานะ — updateDoc ไม่แตะช่องอื่นเลย
      //    และในนี้ต้องไม่มีคำว่า status เด็ดขาด
      await updateDoc(doc(db, "leaveRequests", ใบ.id), { aiSuggestion: สรุป });

      // เก็บทั้งสิ่งที่ส่งไปและสิ่งที่ได้กลับมา ไว้ตอบย้อนหลังว่า
      // "AI เห็นอะไรถึงสรุปออกมาแบบนี้" — ไม่เก็บ input ไว้ ก็ตรวจสอบอะไรไม่ได้เลย
      // ไม่ใส่ช่อง id เพราะบน Firestore id คือชื่อไฟล์ ไม่ใช่ช่องข้อมูล
      await addDoc(collection(db, "leaveRequests", ใบ.id, "aiLog"), {
        input: ข้อความที่ส่งไป,
        output: สรุป,
        createdAt: เวลาตอนนี้()
      });

      ใบ.aiSuggestion = สรุป;                 // เขียนสำเร็จแล้วเท่านั้นถึงเปลี่ยนของบนหน้าจอ
      เอไอ = { กำลังทำ: false, ขั้นที่: "", ปัญหา: "" };
      วาดใบลา();

    } catch (ข้อผิดพลาด) {
      // แยกให้ออกว่าพังตอนคุยกับ AI หรือพังตอนคุยกับฐานข้อมูล
      // เพราะทางแก้คนละเรื่องกันคนละทาง (เปลี่ยนคีย์/รุ่นโมเดล กับ แก้กฎใน firestore.rules)
      // ⚠️ ทั้งสองทางไม่มีทางไหนที่ทำให้สถานะใบลาเปลี่ยน — ขั้นที่ 3 ส่งไปแค่ช่อง aiSuggestion
      เอไอ.กำลังทำ = false;
      เอไอ.ขั้นที่ = "";

      if (ข้อผิดพลาด && ข้อผิดพลาด.code) {
        // มี .code = ข้อผิดพลาดของ Firestore (ของ AI ใช้ช่อง .รหัส คนละช่องกัน)
        เอไอ.ปัญหา = (เอไอตอบแล้ว
          ? "AI สรุปมาแล้ว แต่บันทึกลงฐานไม่สำเร็จ — "
          : "อ่านความเห็นจากฐานไม่สำเร็จ ยังไม่ได้เรียก AI เลย — ") +
          แปลข้อผิดพลาดการเขียน(ข้อผิดพลาด);
      } else {
        เอไอ.ปัญหา = แปลข้อผิดพลาดAI(ข้อผิดพลาด);
      }
      วาดใบลา();
    }
  }

