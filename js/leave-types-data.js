import { db } from "./firebase-init.js";
import { collection, getDocs } from "https://www.gstatic.com/firebasejs/12.18.0/firebase-firestore.js";

// ── อ่านประเภทการลาทั้งหมด ──
// คืนอาร์เรย์ของ { id, name } เรียงตามชื่อแบบภาษาไทย
//
// 🔑 เรียงฝั่งเบราว์เซอร์ ไม่ใช้ orderBy ของ Firestore
//    เพราะ Firestore เรียงตามลำดับไบต์ของ UTF-8 ซึ่งไม่ใช่ลำดับพยัญชนะไทย
//    localeCompare("th") เรียงแบบที่คนไทยคาดหวังจริง และรายการนี้มีไม่กี่รายการ
//    จึงไม่มีเหตุผลต้องให้ฐานเรียงให้
export async function อ่านประเภทการลา() {
  var ผล = await getDocs(collection(db, "leaveTypes"));

  return ผล.docs
    // ไฟล์.id = ชื่อไฟล์ (เช่น "lt001") · ไฟล์.data() = ช่องข้อมูลข้างใน
    // ช่อง id ไม่ได้อยู่ในไฟล์ ต้องแปะกลับเข้ามาเองตอนอ่าน
    .map(function (ไฟล์) {
      return { id: ไฟล์.id, name: String(ไฟล์.data().name || "") };
    })
    .sort(function (a, b) { return a.name.localeCompare(b.name, "th"); });
}

// ── แปลข้อผิดพลาดตอนอ่าน/เขียนประเภทการลา ──
// รวมไว้ที่นี่เพราะทั้งสองหน้าต้องแสดงข้อความชุดเดียวกัน
//
//   ชนิดงาน — "อ่าน" หรือ "แก้ไข" · ต้องบอกมาเสมอเวลาเจอ permission-denied
//
// 🔑 อ่านกับแก้ไขโดนปฏิเสธด้วยเหตุผลคนละข้อ และแก้คนละทาง (ดู firestore.rules)
//      อ่าน   ต้องล็อกอิน           → allow read: if loggedIn()
//      แก้ไข  ต้องเป็นฝ่ายบุคคล      → allow write: if isHR()
//    บอกรวมเป็นข้อความเดียวเมื่อไร คนที่แค่ยังไม่ได้ล็อกอินจะไปนั่งหาว่าทำไมตัวเองไม่ใช่ hr
export function แปลข้อผิดพลาดประเภทการลา(e, ชนิดงาน) {
  var รหัส = (e && e.code) || "";

  if (รหัส === "permission-denied") {
    return ชนิดงาน === "อ่าน"
      ? "กฎความปลอดภัยไม่อนุญาตให้อ่านประเภทการลา — ต้องเข้าสู่ระบบก่อน"
      : "กฎความปลอดภัยไม่อนุญาต — เพิ่ม แก้ ลบ ประเภทการลาได้เฉพาะฝ่ายบุคคล (hr) เท่านั้น";
  }
  if (รหัส === "unavailable" || รหัส === "failed-precondition") {
    return "ต่อฐานข้อมูลไม่ได้ — ตรวจว่าเครื่องต่อเน็ตอยู่ แล้วลองใหม่อีกครั้ง";
  }
  if (รหัส === "not-found") {
    return "ไม่พบฐานข้อมูลของโปรเจกต์นี้ — ตรวจค่าใน js/firebase-init.js";
  }
  return "ทำรายการไม่สำเร็จ — " + ((e && e.message) || String(e));
}
