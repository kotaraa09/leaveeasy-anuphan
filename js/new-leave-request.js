// js/new-leave-request.js — หน้าที่ 2 ยื่นใบลาใหม่
// สัปดาห์ที่ 7: บันทึกลงโฟลเดอร์ leaveRequests บน Firestore ของจริง
//
// 🔑 จุดที่ต้องระวังที่สุดในไฟล์นี้
//    1. ตรวจให้ผ่านครบทุกข้อก่อน แล้วค่อยเขียนลงฐาน
//       ข้อมูลเสียที่เขียนลงไปแล้ว ลบทีหลังยากกว่ากันไว้ตั้งแต่แรกมาก
//    2. ต้องรอ (await) ให้เขียนสำเร็จก่อน ค่อยเปลี่ยนหน้า
//       ถ้าสั่งเปลี่ยนหน้าทันที เบราว์เซอร์จะตัดการเขียนกลางคัน — พังแบบเงียบ ๆ
//    3. ไม่ต้องใส่ช่อง id ลงไป เพราะบน Firestore id คือ "ชื่อไฟล์" ไม่ใช่ช่องข้อมูล
// ─────────────────────────────────────────────────────────────

import { db } from "./firebase-init.js";
import { ต้องล็อกอิน } from "./auth.js";
import { collection, addDoc } from "https://www.gstatic.com/firebasejs/12.18.0/firebase-firestore.js";

(async function () {
  // ยังไม่ล็อกอินก็เด้งไปหน้าเข้าสู่ระบบ โค้ดข้างล่างนี้จะไม่ทำงานต่อ
  // ต้องรู้ว่าใครยื่นก่อนเสมอ เพราะใบลาต้องจดชื่อผู้ขอลาลงไปด้วย
  var ผู้ใช้ = await ต้องล็อกอิน();

  var ฟอร์ม = document.getElementById("ฟอร์มใบลา");
  var ช่องประเภท = document.getElementById("leaveTypeId");
  var กล่องเตือน = document.getElementById("ข้อความเตือน");
  var ปุ่มบันทึก = document.getElementById("ปุ่มบันทึก");

  // ── ขีดจำกัดของแต่ละช่อง รวมไว้ที่เดียว จะได้แก้ที่เดียว ──
  // ตัวเลขพวกนี้ไม่ได้กันคนพิมพ์ผิดเล็กน้อย แต่กัน "พิมพ์ผิดจนข้อมูลใช้ไม่ได้"
  // เช่น หัวข้อเป็นจุดเดียว หรือลายาว 900 วันเพราะพิมพ์ปีผิด
  var กติกา = {
    หัวข้อสั้นสุด: 5,   หัวข้อยาวสุด: 100,
    เหตุผลสั้นสุด: 10,  เหตุผลยาวสุด: 500,
    จำนวนวันมากสุด: 60,
    ย้อนหลังมากสุด: 365,
    ล่วงหน้ามากสุด: 730
  };

  // เติมรายการเลื่อนลงด้วยประเภทการลาที่มีอยู่
  window.LEAVE_DATA.leaveTypes.forEach(function (ประเภท) {
    var ตัวเลือก = document.createElement("option");
    ตัวเลือก.value = ประเภท.id;
    ตัวเลือก.textContent = ประเภท.name;
    ช่องประเภท.appendChild(ตัวเลือก);
  });

  ฟอร์ม.addEventListener("submit", async function (e) {
    e.preventDefault();
    ซ่อนคำเตือน();

    var ค่า = {
      title: document.getElementById("title").value.trim(),
      reason: document.getElementById("reason").value.trim(),
      leaveTypeId: ช่องประเภท.value,
      startDate: document.getElementById("startDate").value,
      endDate: document.getElementById("endDate").value
    };

    // ── ด่านตรวจ ── ไม่ผ่านข้อไหน หยุดทันที ไม่แตะฐานข้อมูลเลย
    var ผลตรวจ = ตรวจฟอร์ม(ค่า);
    if (!ผลตรวจ.ผ่าน) {
      เตือน(ผลตรวจ.ข้อความ, ผลตรวจ.ช่อง);
      return;
    }

    var ประเภท = window.LEAVE_DATA.leaveTypes.find(function (t) { return t.id === ค่า.leaveTypeId; });

    // ผู้ขอลาคือคนที่ล็อกอินอยู่ตอนนี้ — uid คือชื่อไฟล์ของเขาในโฟลเดอร์ users
    // 🔁 จด requesterName ซ้ำไว้ด้วยเสมอ เพราะ Firestore ไม่มี JOIN
    //    ถ้าเก็บแต่ uid หน้ารายการจะขึ้นรหัสยาว ๆ แทนชื่อคน
    var ใบใหม่ = {
      title: ค่า.title,
      reason: ค่า.reason,
      status: "รอพิจารณา",                       // ใบใหม่เริ่มที่ รอพิจารณา เสมอ
      requesterId: ผู้ใช้.uid, requesterName: ผู้ใช้.name,
      approverId: "",      approverName: "",     // ยังไม่ได้กำหนดผู้อนุมัติ
      leaveTypeId: ประเภท.id, leaveTypeName: ประเภท.name,
      startDate: ค่า.startDate,
      endDate: ค่า.endDate,
      createdAt: เวลาตอนนี้()
    };

    กำลังบันทึก(true);
    try {
      // addDoc = เขียนไฟล์ใหม่โดยให้ Firestore ตั้งชื่อไฟล์ให้เอง
      await addDoc(collection(db, "leaveRequests"), ใบใหม่);
      location.href = "leave-requests.html";     // เขียนสำเร็จแล้วเท่านั้นถึงเปลี่ยนหน้า
    } catch (ข้อผิดพลาด) {
      เตือน(แปลข้อผิดพลาด(ข้อผิดพลาด));
      กำลังบันทึก(false);                        // คืนปุ่มให้กดใหม่ได้ ข้อมูลที่กรอกไว้ยังอยู่ครบ
    }
  });

  // ── ด่านตรวจทั้งหมด เรียงจากบนลงล่างตามลำดับช่องในฟอร์ม ──
  // คืนค่า { ผ่าน, ข้อความ, ช่อง } — ช่อง มีไว้พาเคอร์เซอร์ไปหยุดที่ช่องที่ผิด
  function ตรวจฟอร์ม(ค่า) {
    // 1. กรอกครบทุกช่องหรือยัง — บอกชื่อช่องที่ขาด ไม่ใช่บอกลอย ๆ ว่ากรอกไม่ครบ
    var ช่องบังคับ = [
      { คีย์: "title",       ชื่อ: "หัวข้อ" },
      { คีย์: "reason",      ชื่อ: "เหตุผลการลา" },
      { คีย์: "leaveTypeId", ชื่อ: "ประเภทการลา" },
      { คีย์: "startDate",   ชื่อ: "วันที่เริ่มลา" },
      { คีย์: "endDate",     ชื่อ: "วันที่สิ้นสุด" }
    ];
    var ที่ขาด = ช่องบังคับ.filter(function (ช) { return !ค่า[ช.คีย์]; });
    if (ที่ขาด.length > 0) {
      return ไม่ผ่าน(
        "ยังไม่ได้กรอก " + ที่ขาด.map(function (ช) { return ช.ชื่อ; }).join(" · "),
        ที่ขาด[0].คีย์
      );
    }

    // 2. หัวข้อ — สั้นจนไม่สื่อความ หรือยาวจนตารางหน้ารายการเสียรูป
    if (ค่า.title.length < กติกา.หัวข้อสั้นสุด) {
      return ไม่ผ่าน("หัวข้อสั้นเกินไป — ต้องมีอย่างน้อย " + กติกา.หัวข้อสั้นสุด + " ตัวอักษร", "title");
    }
    if (ค่า.title.length > กติกา.หัวข้อยาวสุด) {
      return ไม่ผ่าน("หัวข้อยาวเกินไป — ไม่เกิน " + กติกา.หัวข้อยาวสุด + " ตัวอักษร " +
                     "(ตอนนี้ " + ค่า.title.length + ") ให้ย้ายรายละเอียดไปไว้ในช่องเหตุผล", "title");
    }

    // 3. เหตุผล — หัวหน้าต้องอ่านแล้วตัดสินใจได้ คำว่า "ลา" คำเดียวจึงไม่พอ
    if (ค่า.reason.length < กติกา.เหตุผลสั้นสุด) {
      return ไม่ผ่าน("เหตุผลสั้นเกินไป — เขียนอย่างน้อย " + กติกา.เหตุผลสั้นสุด + " ตัวอักษร " +
                     "ให้หัวหน้าพอเข้าใจว่าลาเพราะอะไร", "reason");
    }
    if (ค่า.reason.length > กติกา.เหตุผลยาวสุด) {
      return ไม่ผ่าน("เหตุผลยาวเกินไป — ไม่เกิน " + กติกา.เหตุผลยาวสุด + " ตัวอักษร " +
                     "(ตอนนี้ " + ค่า.reason.length + ")", "reason");
    }

    // 4. ประเภทการลา — ต้องเป็นรหัสที่มีอยู่จริง
    //    ถ้าไม่ตรวจ ค่าที่ถูกแก้ในเบราว์เซอร์จะทำให้ leaveTypeName ว่าง แล้วตารางขึ้นช่องโหว่
    var ประเภท = window.LEAVE_DATA.leaveTypes.find(function (t) { return t.id === ค่า.leaveTypeId; });
    if (!ประเภท) {
      return ไม่ผ่าน("ประเภทการลาที่เลือกไม่มีอยู่ในระบบ — เลือกใหม่อีกครั้ง", "leaveTypeId");
    }

    // 5. วันที่ต้องเป็นวันที่ที่มีอยู่จริง เช่น 2026-02-31 ไม่มีในปฏิทิน
    var เริ่ม = อ่านวันที่(ค่า.startDate);
    var สิ้นสุด = อ่านวันที่(ค่า.endDate);
    if (!เริ่ม)   return ไม่ผ่าน("วันที่เริ่มลาไม่ถูกต้อง — เลือกจากปฏิทินอีกครั้ง", "startDate");
    if (!สิ้นสุด) return ไม่ผ่าน("วันที่สิ้นสุดไม่ถูกต้อง — เลือกจากปฏิทินอีกครั้ง", "endDate");

    // 6. ลำดับวันที่
    if (สิ้นสุด < เริ่ม) {
      return ไม่ผ่าน("วันที่สิ้นสุดต้องไม่มาก่อนวันที่เริ่มลา", "endDate");
    }

    // 7. ความยาวของช่วงลา — ลาวันเดียวนับเป็น 1 วัน
    var จำนวนวัน = ห่างกันกี่วัน(เริ่ม, สิ้นสุด) + 1;
    if (จำนวนวัน > กติกา.จำนวนวันมากสุด) {
      return ไม่ผ่าน("ช่วงที่ขอลายาว " + จำนวนวัน + " วัน เกิน " + กติกา.จำนวนวันมากสุด + " วัน " +
                     "— ตรวจวันที่อีกครั้งว่าพิมพ์ปีหรือเดือนถูกไหม", "endDate");
    }

    // 8. ปีที่พิมพ์ผิดจะโผล่ตรงนี้ (เช่น 2062 แทน 2026)
    //    ไม่ห้ามลาย้อนหลัง เพราะลาป่วยมักยื่นหลังหยุดจริง แค่กันกรณีที่ห่างจนผิดสังเกต
    var วันนี้ = อ่านวันที่(เวลาตอนนี้().slice(0, 10));
    var ห่างจากวันนี้ = ห่างกันกี่วัน(วันนี้, เริ่ม);
    if (ห่างจากวันนี้ < -กติกา.ย้อนหลังมากสุด) {
      return ไม่ผ่าน("วันที่เริ่มลาย้อนหลังเกิน 1 ปี — ตรวจว่าพิมพ์ปีถูกต้องไหม", "startDate");
    }
    if (ห่างจากวันนี้ > กติกา.ล่วงหน้ามากสุด) {
      return ไม่ผ่าน("วันที่เริ่มลาล่วงหน้าเกิน 2 ปี — ตรวจว่าพิมพ์ปีถูกต้องไหม", "startDate");
    }

    return { ผ่าน: true };
  }

  function ไม่ผ่าน(ข้อความ, ช่อง) {
    return { ผ่าน: false, ข้อความ: ข้อความ, ช่อง: ช่อง };
  }

  // ── แปลงข้อความ YYYY-MM-DD เป็นวันที่ · คืน null ถ้าไม่ใช่วันที่ที่มีจริง ──
  function อ่านวันที่(ข้อความ) {
    var ส่วน = /^(\d{4})-(\d{2})-(\d{2})$/.exec(ข้อความ || "");
    if (!ส่วน) return null;

    var ปี = Number(ส่วน[1]), เดือน = Number(ส่วน[2]), วัน = Number(ส่วน[3]);
    var d = new Date(ปี, เดือน - 1, วัน);

    // ถ้าใส่ 31 กุมภา JavaScript จะเลื่อนไปเป็น 3 มีนาให้เอง — เทียบกลับจึงจับได้
    if (d.getFullYear() !== ปี || d.getMonth() !== เดือน - 1 || d.getDate() !== วัน) return null;
    return d;
  }

  function ห่างกันกี่วัน(จาก, ถึง) {
    return Math.round((ถึง - จาก) / 86400000);
  }

  // ── แปลข้อผิดพลาดของ Firebase ให้อ่านรู้เรื่อง ──
  function แปลข้อผิดพลาด(e) {
    var รหัส = (e && e.code) || "";

    if (รหัส === "permission-denied") {
      return "Firestore ปฏิเสธการเขียน — กฎความปลอดภัยยังปิดอยู่ " +
             "ให้เข้า Firebase Console → Firestore Database → แท็บ Rules แล้วตรวจว่าเลือก Test mode ไว้";
    }
    if (รหัส === "unavailable" || รหัส === "failed-precondition") {
      return "ต่อฐานข้อมูลไม่ได้ — ตรวจว่าเครื่องต่อเน็ตอยู่ แล้วกดบันทึกอีกครั้ง ข้อมูลที่กรอกไว้ยังอยู่";
    }
    if (รหัส === "not-found") {
      return "ไม่พบฐานข้อมูลของโปรเจกต์นี้ — ตรวจค่าใน js/firebase-init.js";
    }
    if (รหัส === "invalid-argument") {
      return "ข้อมูลบางช่องมีรูปแบบที่ Firestore รับไม่ได้ — ลองกรอกใหม่อีกครั้ง";
    }
    return "บันทึกไม่สำเร็จ — " + ((e && e.message) || String(e));
  }

  // ── ระหว่างเขียนลงฐาน ปิดปุ่มไว้ กันกดซ้ำแล้วได้ใบลาซ้ำ 2 ใบ ──
  function กำลังบันทึก(อยู่) {
    ปุ่มบันทึก.disabled = อยู่;
    ปุ่มบันทึก.textContent = อยู่ ? "กำลังบันทึก…" : "บันทึก";
  }

  function เตือน(ข้อความ, ช่อง) {
    กล่องเตือน.textContent = "⚠️ " + ข้อความ;
    กล่องเตือน.classList.remove("hidden");

    // พาเคอร์เซอร์ไปหยุดที่ช่องที่ผิด ผู้ใช้จะได้ไม่ต้องไล่หาเองว่าช่องไหน
    if (ช่อง) {
      var ที่ผิด = document.getElementById(ช่อง);
      if (ที่ผิด) ที่ผิด.focus();
    }
  }

  function ซ่อนคำเตือน() {
    กล่องเตือน.classList.add("hidden");
  }
})();
