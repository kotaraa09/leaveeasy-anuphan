// ─────────────────────────────────────────────────────────────
// js/nav.js — แถบเมนูด้านบนที่ใช้ร่วมกันทุกหน้า
// แก้เมนูที่ไฟล์นี้ที่เดียว ทุกหน้าเปลี่ยนตามพร้อมกัน
//
// วิธีใช้: ทุกหน้ามี <div id="nav"></div> ไว้บนสุดของ body
//          และต้องโหลด js/icons.js ก่อนไฟล์นี้เสมอ (แถบเมนูใช้ไอคอนจากที่นั่น)
//
// แถบนี้เกาะขอบบนไว้ตลอดและพื้นหลังโปร่งแสงเบลอ (ดู .navbar ใน css/style.css)
// เนื้อหาที่เลื่อนผ่านข้างใต้จะเห็นเป็นเงาราง ๆ ผู้ใช้จึงรู้ว่ายังมีของอยู่ข้างบน
// ─────────────────────────────────────────────────────────────

(function () {
  // เฉพาะบทบาท = เมนูนี้ให้เห็นเฉพาะบทบาทที่ระบุ (ตาม ACL.md) · ไม่ใส่ = ทุกคนเห็น
  // ตัวเมนูถูกวาดพร้อมคลาส hidden ไว้ก่อน แล้ว js/auth.js จะเปิดให้เห็นเมื่อรู้ว่าบทบาทตรงกัน
  var เมนู = [
    { href: "index.html",             ชื่อ: "หน้าแรก",     ไอคอน: "แดชบอร์ด" },
    { href: "leave-requests.html",    ชื่อ: "รายการใบลา",  ไอคอน: "รายการ" },
    { href: "new-leave-request.html", ชื่อ: "ยื่นใบลาใหม่", ไอคอน: "เพิ่ม" },
    { href: "leave-types.html",       ชื่อ: "ประเภทการลา", ไอคอน: "ป้าย", เฉพาะบทบาท: "hr" }
  ];

  // ชื่อหน้าแบบตัด .html ออก เอาไว้เทียบว่าตอนนี้อยู่หน้าไหน
  //
  // ต้องตัด .html ทิ้งก่อนเทียบ เพราะเซิร์ฟเวอร์ที่ใช้ตอนพัฒนา (serve) จะเปลี่ยน
  // /leave-requests.html ให้กลายเป็น /leave-requests ให้เองอัตโนมัติ
  // ถ้าเอา "leave-requests" ไปเทียบกับ "leave-requests.html" ตรง ๆ จะไม่ตรงสักอัน
  // แล้วเมนูที่เปิดอยู่จะไม่ถูกเน้นสีเลยสักหน้า
  function ชื่อหน้า(ที่อยู่) {
    return (ที่อยู่.split("/").pop() || "index").replace(/\.html$/, "");
  }

  // หน้าที่ไม่มีเมนูของตัวเอง แต่เป็นหน้าลูกของเมนูอื่น
  // เปิดหน้ารายละเอียดใบลาอยู่ ก็ให้เน้นที่ "รายการใบลา" จะได้รู้ว่าตัวเองอยู่ตรงไหน
  var หน้าลูกของ = {
    "leave-request-detail": "leave-requests"
  };

  // หน้าที่เหลือแต่เครื่องหมาย ไม่มีเมนูและไม่มีชื่อคนที่ล็อกอินอยู่
  //
  // คนที่อยู่หน้าเข้าสู่ระบบคือคนที่ยังไม่ได้ล็อกอิน กดเมนูอื่นไปก็โดน js/auth.js
  // เด้งกลับมาหน้านี้อยู่ดี เมนูที่กดแล้วไม่พาไปไหนจึงไม่ควรมีตั้งแต่แรก
  // เหลือเครื่องหมายอย่างเดียว ไว้บอกว่านี่ยังเป็น LeaveEasy อยู่ และกดกลับหน้าแรกได้
  var หน้าที่เหลือแต่เครื่องหมาย = ["login", "signup"];

  var หน้าปัจจุบัน = ชื่อหน้า(location.pathname);
  หน้าปัจจุบัน = หน้าลูกของ[หน้าปัจจุบัน] || หน้าปัจจุบัน;

  var แถบเปล่า =
    หน้าที่เหลือแต่เครื่องหมาย.indexOf(หน้าปัจจุบัน) !== -1;

  var html =
    '<nav class="navbar" aria-label="เมนูหลัก"><div class="navbar-in">' +
    '<a class="brand" href="index.html">' + window.เครื่องหมายLeaveEasy() +
    "<span>LeaveEasy</span></a>";

  // หน้าเข้าสู่ระบบกับสมัครสมาชิก จบแค่เครื่องหมายเท่านั้น
  if (แถบเปล่า) {
    วางแถบ(html + "</div></nav>");
    return;
  }

  html += '<div class="nav-links">';

  เมนู.forEach(function (m) {
    var คลาส = [];
    if (ชื่อหน้า(m.href) === หน้าปัจจุบัน) คลาส.push("active");

    // เมนูที่จำกัดบทบาท ต้องซ่อนไว้ก่อนเสมอ กว่าจะรู้บทบาทหน้าจอวาดเสร็จไปแล้ว
    var ป้ายบทบาท = "";
    if (m.เฉพาะบทบาท) {
      คลาส.push("hidden");
      ป้ายบทบาท = ' data-เฉพาะบทบาท="' + m.เฉพาะบทบาท + '"';
    }

    // aria-current บอกโปรแกรมอ่านหน้าจอว่าอันนี้คือหน้าที่เปิดอยู่ — สีอย่างเดียวไม่พอ
    // aria-label ต้องมีเสมอ เพราะบนจอมือถือชื่อเมนูถูกซ่อน เหลือแต่ไอคอน
    html += '<a href="' + m.href + '" class="' + คลาส.join(" ") + '"' + ป้ายบทบาท +
            ' aria-label="' + m.ชื่อ + '"' +
            (ชื่อหน้า(m.href) === หน้าปัจจุบัน ? ' aria-current="page"' : "") + ">" +
            window.ไอคอน(m.ไอคอน) + "<span>" + m.ชื่อ + "</span></a>";
  });

  // ช่องว่างสำหรับชื่อคนที่ล็อกอินอยู่ + ปุ่มออกจากระบบ · js/auth.js เป็นคนเติมให้
  html += '</div><div class="nav-user" id="navUser"></div></div></nav>';

  วางแถบ(html);

  // เอา <div id="nav"> ออกแล้วเอาแถบเมนูจริงไปวางแทนที่
  // หน้าไหนไม่มีที่วางนี้ ก็ไม่ต้องมีแถบเมนู ไม่ใช่ข้อผิดพลาด
  function วางแถบ(เนื้อหา) {
    var ที่วาง = document.getElementById("nav");
    if (ที่วาง) ที่วาง.outerHTML = เนื้อหา;
  }
})();

// แถบเตือนสีเหลือง ใช้ตอนที่ยังไม่ได้ตั้งค่า Firebase
function showConfigWarning(ข้อความ) {
  var กล่อง = document.createElement("div");
  กล่อง.className = "alert alert-warn";
  กล่อง.innerHTML =
    window.ไอคอน("เตือน") +
    "<div><b>ยังไม่ได้ตั้งค่า Firebase</b> — " +
    (ข้อความ || "หน้านี้จึงยังไม่ได้อ่านข้อมูลจากฐานข้อมูลจริง") +
    "<br>วิธีตั้งค่าอยู่ในไฟล์ SETUP.md ขั้นที่ 4</div>";

  // .auth คือกรอบเนื้อหาของหน้าเข้าสู่ระบบกับสมัครสมาชิก ซึ่งไม่ได้ใช้ .container
  // ถ้าไม่นับมันด้วย คำเตือนจะไปโผล่เหนือแถบเมนูของสองหน้านั้น
  var ที่วาง = document.querySelector(".container, .auth") || document.body;
  ที่วาง.insertBefore(กล่อง, ที่วาง.firstChild);
}
